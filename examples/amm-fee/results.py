"""Write RESULTS.md from the records check.sh leaves in runs/. Standard library only.

Usage:  python3 examples/amm-fee/results.py      (check.sh runs it last)

Every figure in RESULTS.md is read from a file a script wrote:
    out/model.json ("metrics"), model/*.json ("task", "training")   export.py, train.py
    runs/arbiter-gas.json, runs/network-gas.json, runs/oracle-gas.json   this run, on anvil
    runs/sizes.json, runs/native.txt, runs/steps.tsv                      sizes, native differential, timings
    ../mnist-784-128-64-10/runs/*.json                                    the two MNIST models, as committed
Nothing is typed in by hand; the sentences are templates filled from the same numbers, and the
comparisons ("more", "fewer", "does not pay") are computed, not assumed.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, HERE)

import dataset  # noqa: E402
from gen_tree import commitment  # noqa: E402

CAP = 16777216  # the Osaka limit of one transaction
MNIST = os.path.join(ROOT, "examples", "mnist-784-128-64-10")


def load(*parts):
    with open(os.path.join(*parts), "r", encoding="utf-8") as f:
        return json.load(f)


def n(value):
    return "{:,}".format(value)


def pct(part, whole):
    return "%.1f%%" % (100.0 * part / whole)


def share(part, whole):
    return "%s of %s (%.2f%%)" % (n(part), n(whole), 100.0 * part / whole)


def calls_by_name(record):
    return {call["call"]: call for call in record["calls"]}


def first_challenge(record):
    """The layer 1 challenge as the first slash of the run: the dearest a dispute gets."""
    return next(call for call in record["calls"] if call["call"].startswith("challengeNeuron1"))


def gas_column(arbiter, network):
    calls = calls_by_name(arbiter)
    honest = calls["claim"]["gas_used"] + calls["finalize"]["gas_used"]
    return {"whole": network["classify"]["gas_used"], "claim": calls["claim"]["gas_used"],
            "finalize": calls["finalize"]["gas_used"], "honest": honest,
            "dearest": first_challenge(arbiter)["gas_used"], "runtime": arbiter["arbiter_runtime_bytes"]}


def params(model):
    return sum(layer["in"] * layer["out"] + layer["out"] for layer in model["layers"])


def arrow(model):
    return " -> ".join(str(v) for v in [model["layers"][0]["in"]] + [layer["out"] for layer in model["layers"]])


def main():
    model = load(HERE, "out", "model.json")
    trained = load(dataset.MODEL_PATH)
    task, training, m = trained["task"], trained["training"], model["metrics"]
    arbiter, network = load(HERE, "runs", "arbiter-gas.json"), load(HERE, "runs", "network-gas.json")
    oracle = load(HERE, "runs", "oracle-gas.json")
    sizes = load(HERE, "runs", "sizes.json")
    tree = commitment(model)
    calls = calls_by_name(arbiter)
    this = gas_column(arbiter, network)
    with open(os.path.join(HERE, "runs", "steps.tsv"), "r", encoding="utf-8") as f:
        steps = [line.rstrip("\n").split("\t") for line in f if line.strip()]
    with open(os.path.join(HERE, "runs", "native.txt"), "r", encoding="utf-8") as f:
        native = [line.rstrip("\n") for line in f if line.strip()]
    total = next(row for row in steps if row[0] == "total")
    tests = m["test_samples"]
    last_block = task["first_block"] + task["step_blocks"] * (task["ticks"] - 1)

    out = []
    add = out.append
    add("# Results: a fee tier from the pool's own ticks, %s" % arrow(model))
    add("")
    add("Generated by `check.sh` (its last step, `results.py`) from the records in `runs/`, `out/` and `model/`.")
    add("Change the scripts or the code, never this file. Gas is from real transactions on anvil (Osaka), test")
    add("sample 0 (section 3), each result checked against the NumPy reference or the protocol before its gas is recorded.")
    add("%s; whole `check.sh` run: %s s." % (total[2], total[1]))
    add("")
    add("## 1. The task and the model")
    add("")
    add("| | |")
    add("|---|---|")
    add("| Data | %s |" % task["pool"])
    add("| Series | the pool's tick (`slot0`) at the end of every %dth block, blocks %s to %s: %s ticks "
        "(`data/ticks.csv`, sha256 `%s`) |" % (task["step_blocks"], n(task["first_block"]), n(last_block),
                                                n(task["ticks"]), task["ticks_sha256"]))
    add("| Input | the last %d moves, each `min(\\|tick - previous tick\\|, %d)`, one byte each |"
        % (task["n_obs"], task["clip"]))
    add("| Target | the tier of the sum of the %d moves that start %d moves after the input ends |"
        % (task["horizon"], task["gap"]))
    add("| Tiers | sum below %s: tier 0; below %s: tier 1; else tier 2 (quantiles of the training split only) |"
        % (n(task["thresholds"][0]), n(task["thresholds"][1])))
    add("| Split, in time order | training moves %s, validation %s, test %s |" % tuple(
        "%s to %s" % (n(lo), n(hi)) for lo, hi in (task["split_moves"][k] for k in ("train", "validation", "test"))))
    add("| Network | %s, dense, ReLU by clamp to 0..127 |" % arrow(model))
    add("| Parameters | %s weights (int8) and %s biases (int32) |" % (
        n(sum(layer["in"] * layer["out"] for layer in model["layers"])), n(sum(layer["out"] for layer in model["layers"]))))
    add("| Training | `train.py`: seed %d, NumPy %s, %d float epochs (epoch %d kept, by validation), post-training "
        "quantisation, %s training samples |" % (training["seed"], training["numpy"], training["float_epochs"],
                                                 training["kept_epoch"], n(training["train_samples"])))
    add("| Model root (what the arbiter is deployed with) | `%s` |" % tree["root"])
    add("")
    add("| Layer | Size | Weight fractional bits | Shift | Worst-case accumulator (int32 maximum 2,147,483,647) |")
    add("|---|---|---|---|---|")
    for index, layer in enumerate(model["layers"], start=1):
        add("| %d | %d -> %d | %d | %s | %s, proved by a `static_assert` in `ingots/model/src/layer%d.fe` |" % (
            index, layer["in"], layer["out"], layer["weight_frac_bits"],
            "none (logits)" if layer["shift"] is None else layer["shift"], n(layer["worst_case_abs_acc"]), index))
    add("")
    add("## 2. Scores on the held-out test split")
    add("")
    add("The test split is the last 15% of the series in time. It was scored once, by `export.py`; no choice")
    add("was made on it. Every count below is recomputed by `check.sh` (step 1) from the committed predictions")
    add("and the labels rebuilt from the ticks. Consecutive samples overlap (one starts every 10 minutes and")
    add("each spans %d moves), so the %s samples are far from independent: read differences of a few"
        % (task["n_obs"] + task["gap"] + task["horizon"], n(tests)))
    add("tens of samples as noise.")
    add("")
    add("| Predictor | Correct tier | Within one tier |")
    add("|---|---|---|")
    add("| **The integer model** (what the arbiter enforces) | %s | %s |"
        % (share(m["model_correct"], tests), share(m["model_within_one_tier"], tests)))
    add("| Persistence: the tier of the last %d moves of the input | %s | %s |"
        % (task["horizon"], share(m["persistence_correct"], tests), share(m["persistence_within_one_tier"], tests)))
    add("| Majority: always tier %d, the most common tier of the test split itself | %s | |"
        % (m["majority_tier"], share(m["majority_correct"], tests)))
    add("")
    add("| Tier | Test samples | Model recall | Persistence recall | Times the model answered it |")
    add("|---|---|---|---|---|")
    for row in m["per_tier"]:
        add("| %d | %s | %s | %s | %s |" % (row["tier"], n(row["labels"]), share(row["model_correct"], row["labels"]),
                                            share(row["persistence_correct"], row["labels"]), n(row["model_answers"])))
    add("")
    add("Confusion, rows the true tier and columns the model's answer: `%s`." % m["confusion_label_by_answer"])
    add("")
    diff = m["model_correct"] - m["persistence_correct"]
    v = training["validation"]
    add("- On the test split the model is right %s often than persistence (%+d samples, %+.2f percentage"
        % ("more" if diff > 0 else "less" if diff < 0 else "exactly as", diff, 100.0 * diff / tests))
    add("  points) and right %s the best constant answer (%+d samples)."
        % ("more often than" if m["model_correct"] > m["majority_correct"] else
           "less often than" if m["model_correct"] < m["majority_correct"] else "exactly as often as",
           m["model_correct"] - m["majority_correct"]))
    add("- On the validation split, which chose the epoch and the scales: model %s, persistence %s, the"
        % (share(v["integer_correct"], v["samples"]), share(v["persistence_correct"], v["samples"])))
    add("  training split's majority tier %s; the float model before quantisation %s."
        % (share(v["majority_correct"], v["samples"]), share(v["float_correct"], v["samples"])))
    weakest = min(m["per_tier"], key=lambda row: row["model_correct"] / max(row["labels"], 1))
    add("- Unflattering: the model's weakest tier is tier %d, where it is right for %s."
        % (weakest["tier"], share(weakest["model_correct"], weakest["labels"])))
    add("")
    add("## 3. Gas: what the dispute costs and what it saves at this size")
    add("")
    add("The first column is this model. The other two are the MNIST models of this repository, read from the")
    add("records committed in `examples/mnist-784-128-64-10/runs/` (measured by the same two scripts, in that")
    add("example's own run), so that the effect of model size is visible. Every figure is measured.")
    add("")
    m1 = gas_column(load(MNIST, "runs", "model1-arbiter-gas.json"), load(MNIST, "runs", "model1-network-gas.json"))
    m2 = gas_column(load(MNIST, "runs", "arbiter-gas.json"), load(MNIST, "runs", "network-gas.json"))
    p1, p2 = params(load(ROOT, "ref", "out", "model.json")), params(load(MNIST, "out", "model.json"))
    cols = (this, m1, m2)
    add("| | %s (this example) | 784 -> 32 -> 10 | 784 -> 128 -> 64 -> 10 |" % arrow(model))
    add("|---|---|---|---|")
    add("| Parameters (weights and biases) | %s | %s | %s |" % (n(params(model)), n(p1), n(p2)))
    add("| Whole forward pass on-chain, `Network.classify`, gas | %s | %s | %s |" % tuple(n(c["whole"]) for c in cols))
    add("| `claim`, gas | %s | %s | %s |" % tuple(n(c["claim"]) for c in cols))
    add("| `finalize`, gas | %s | %s | %s |" % tuple(n(c["finalize"]) for c in cols))
    add("| Honest path, `claim` + `finalize`, gas | %s | %s | %s |" % tuple(n(c["honest"]) for c in cols))
    add("| the same, as a share of one whole forward pass | %s | %s | %s |" % tuple(pct(c["honest"], c["whole"]) for c in cols))
    add("| Dearest dispute (layer 1 neuron, first slash ever), gas | %s | %s | %s |" % tuple(n(c["dearest"]) for c in cols))
    add("| the same, as a share of one whole forward pass | %s | %s | %s |" % tuple(pct(c["dearest"], c["whole"]) for c in cols))
    add("| `Arbiter` deployed bytes (limit 24,576) | %s | %s | %s |" % tuple(n(c["runtime"]) for c in cols))
    add("")
    add("This model's calls, one by one (`runs/arbiter-gas.json`):")
    add("")
    add("| Call | Gas used | Execution gas | Calldata bytes |")
    add("|---|---|---|---|")
    for call in arbiter["calls"]:
        add("| `%s` | %s | %s | %s |" % (call["call"], n(call["gas_used"]), n(call["execution"]), n(call["calldata_bytes"])))
    add("")
    add("A \"later\" challenge is the same challenge when the challenger's credit and the contract's `burned`")
    add("total are already non-zero; the first slash of a run pays %s gas more for those two slots."
        % n(this["dearest"] - calls["later challengeNeuron1 (%d inputs)" % model["layers"][0]["in"]]["gas_used"]))
    add("")
    route = this["honest"] + oracle["apply_later"]
    add("### What the numbers show")
    add("")
    add("- **Unflattering: a model this small does not need the dispute.** The honest path costs %s gas, %s of"
        % (n(this["honest"]), pct(this["honest"], this["whole"])))
    add("  the %s that running the whole network on-chain costs. The consumer must also check the claim's input"
        % n(this["whole"]))
    add("  (`apply`, %s gas after the first, section 4), so one decision by the claim route costs %s gas: %s"
        % (n(oracle["apply_later"]), n(route),
           "%s more than the whole run" % n(route - this["whole"]) if route > this["whole"]
           else "%s less than the whole run" % n(this["whole"] - route) if route < this["whole"]
           else "exactly the whole run"))
    add("  (which would still need a transaction of its own to store the fee; that was not measured). A claim has")
    add("  a fixed cost (a record of eight storage slots, the event, the bond) that a network of %s parameters"
        % n(params(model)))
    add("  hardly outweighs, and the claim route adds a bond, a window and a watcher.")
    add("- **The saving comes with size.** The same honest path is %s of a whole run for %s parameters and %s"
        % (pct(m1["honest"], m1["whole"]), n(p1), pct(m2["honest"], m2["whole"])))
    add("  for %s, because the claim grows with the layer widths (%s, %s and %s gas) while the whole run grows"
        % (n(p2), n(this["claim"]), n(m1["claim"]), n(m2["claim"])))
    add("  with the number of weights (%s, %s and %s gas). A fee model with a longer history or wider layers"
        % (n(this["whole"]), n(m1["whole"]), n(m2["whole"])))
    add("  moves along that line; this example does not claim such a model would predict better.")
    add("- **A dispute is still one neuron.** The dearest challenge here costs %s gas, %s of the whole run."
        % (n(this["dearest"]), pct(this["dearest"], this["whole"])))
    add("  The cheapest, `challengeClass`, costs %s: below a few hundred inputs the fixed part dominates."
        % n(calls["later challengeClass"]["gas_used"]))
    add("")
    add("## 4. The consumer: `FeeOracle` on the real ticks of test sample %d (`oracle_check.sh`)" % oracle["sample"])
    add("")
    add("A test pool answered `slot0()` with the %d real ticks behind test sample %d (the first whose reference tier"
        % (task["n_obs"] + 1, oracle["sample"]))
    add("is not the middle one, so that the fee leaves its default of 3,000), one every %d mined"
        % oracle["interval_blocks"])
    add("blocks. The packed input the contract built from them equals that sample in `out/inputs.bin`; the honest")
    add("claim about it was finalised after its window and applied: tier %d, `fee()` %s (hundredths of a basis"
        % (oracle["tier"], n(oracle["fee"])))
    add("point). After one more observation the next sample's window, which starts inside a stored word, also")
    add("equalled `out/inputs.bin`, and its claim set tier %d, `fee()` %s. An observation inside the interval, an"
        % (oracle["next_tier"], n(oracle["next_fee"])))
    add("open claim, a second `apply` of one window and a claim applied to the wrong window were each refused.")
    add("")
    add("| Call | Gas used |")
    add("|---|---|")
    add("| `observe()`, the first (stores the starting tick only) | %s |" % n(oracle["observe_first"]))
    add("| `observe()`, the %d after it: median, lowest, highest | %s, %s, %s |"
        % (oracle["observations"] - 1, n(oracle["observe_median"]), n(oracle["observe_min"]), n(oracle["observe_max"])))
    add("| `apply(id, end)`, the first: rebuild and hash the window, two reads of the arbiter, three fresh slots | %s |" % n(oracle["apply"]))
    add("| `apply(id, end)`, the next one | %s |" % n(oracle["apply_later"]))
    add("| `fee()` (estimate of a transaction; a hook would pay less, as an internal call) | %s |" % n(oracle["fee_estimate"]))
    add("")
    per_window = oracle["observe_median"] * task["horizon"]
    add("One fee decision every %d intervals therefore costs about %s gas of observations (%d times the median),"
        % (task["horizon"], n(per_window), task["horizon"]))
    add("%s for the honest claim and %s to apply it: %s in all. The observations are %s of that, and they"
        % (n(this["honest"]), n(oracle["apply_later"]), n(per_window + route), pct(per_window, per_window + route)))
    add("would cost the same if the network were run on-chain directly. Unflattering: `observe()` is written to")
    add("be read, not to be cheap (a call to the pool, five storage writes and an event each time); what a")
    add("hook that already holds the tick would pay was not measured. These sums are arithmetic on the rows")
    add("above, not separate measurements.")
    add("")
    add("## 5. The checks behind this file (`check.sh`, one run)")
    add("")
    add("| Step | Result | Wall time | Last line of its output |")
    add("|---|---|---|---|")
    for status, seconds, name, detail in (row for row in steps if row[0] != "total"):
        add("| %s | %s | %s s | %s |" % (name, status, seconds, detail.replace("|", "\\|")))
    add("")
    add("The model ingot's tests are the first %s test samples (two tests each: layer by layer, and neuron by"
        % total[3])
    add("neuron through `neuron_from_words`, the function the arbiter calls), on the EVM backend and again")
    add("natively. The native classifier against the NumPy reference on the whole test split:")
    add("")
    add("```")
    out.extend(native)
    add("```")
    add("")
    add("## 6. Runtime sizes (`fe build`, limit 24,576 bytes)")
    add("")
    add("| Contract | Runtime bytes | Under the limit by |")
    add("|---|---|---|")
    for name, size in sizes.items():
        add("| `%s` | %s | %s |" % (name, n(size), n(24576 - size)))
    add("")
    add("`FeeOracle` is the consumer (`ingots/consumer`), `TestPool` its test double, `Wallet` a test double from")
    add("the arbiter's tests, `Rows0` and `Network` the whole forward pass on-chain.")
    add("")
    with open(os.path.join(HERE, "RESULTS.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote RESULTS.md (%d lines)" % len(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
