"""Write RESULTS.md from the records check.sh leaves in runs/. Standard library only.

Usage:  python3 examples/mnist-784-128-64-10/results.py      (check.sh runs it last)

Every figure in RESULTS.md is read from a file a script wrote during a run:
    runs/arbiter-gas.json, runs/network-gas.json                 this model, on anvil
    runs/model1-arbiter-gas.json, runs/model1-network-gas.json   the shipped model, same scripts
    runs/sizes.json, runs/native.txt, runs/steps.tsv             sizes, native differential, timings
    out/model.json, ref/out/model.json, model/*.json             the two models and the training record
Nothing is typed in by hand; the sentences under the tables are templates filled from the same
numbers, and say only what a subtraction or a ratio of those numbers says.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tools"))

from gen_tree import commitment  # noqa: E402

CAP = 16777216  # the Osaka limit of one transaction


def load(*parts):
    with open(os.path.join(*parts), "r", encoding="utf-8") as f:
        return json.load(f)


def n(value):
    return "{:,}".format(value)


def pct(part, whole):
    return "%.1f%%" % (100.0 * part / whole)


def describe(model):
    sizes = [model["layers"][0]["in"]] + [layer["out"] for layer in model["layers"]]
    tree = commitment(model)
    proofs = [len(leaf["proof"]) for leaf in tree["leaves"]]
    return {
        "sizes": sizes,
        "arrow": " -> ".join(str(v) for v in sizes),
        "weights": sum(layer["in"] * layer["out"] for layer in model["layers"]),
        "biases": sum(sizes[1:]),
        "neurons": sum(sizes[1:]),
        "proof": (min(proofs), max(proofs)),
        "root": tree["root"],
    }


def proof_nodes(model, layer, neuron=0):
    """Length of the Merkle proof of one neuron (the gas script challenges neuron 0 of each layer)."""
    for leaf in commitment(model)["leaves"]:
        if leaf["layer"] == layer and leaf["neuron"] == neuron:
            return len(leaf["proof"])


def calls_by_name(record):
    return {call["call"]: call for call in record["calls"]}


def challenges(record, prefix="later "):
    """[(layer, fan-in, call)] of the neuron challenges, in layer order. With the default prefix,
    the second measurement of each (credit and `burned` slots already non-zero), which is the same
    storage state for every layer; with "", the first, where challengeNeuron1 is the first slash of
    the run."""
    out = []
    for call in record["calls"]:
        if call["call"].startswith(prefix + "challengeNeuron"):
            layer = int(call["call"][len(prefix + "challengeNeuron"):].split(" ")[0])
            fan_in = int(call["call"].split("(")[1].split(" ")[0])
            out.append((layer, fan_in, call))
    return out


def main():
    m1 = load(ROOT, "ref", "out", "model.json")
    m2 = load(HERE, "out", "model.json")
    trained = load(HERE, "model", m2["name"] + ".json")
    d1, d2 = describe(m1), describe(m2)
    a1, a2 = load(HERE, "runs", "model1-arbiter-gas.json"), load(HERE, "runs", "arbiter-gas.json")
    w1, w2 = load(HERE, "runs", "model1-network-gas.json"), load(HERE, "runs", "network-gas.json")
    sizes = load(HERE, "runs", "sizes.json")
    c1, c2 = calls_by_name(a1), calls_by_name(a2)
    full1, full2 = w1["classify"]["gas_used"], w2["classify"]["gas_used"]
    with open(os.path.join(HERE, "runs", "steps.tsv"), "r", encoding="utf-8") as f:
        steps = [line.rstrip("\n").split("\t") for line in f if line.strip()]
    with open(os.path.join(HERE, "runs", "native.txt"), "r", encoding="utf-8") as f:
        native = [line.rstrip("\n") for line in f if line.strip()]
    total = next(row for row in steps if row[0] == "total")

    out = []
    add = out.append
    add("# Results: %s beside the shipped %s" % (d2["arrow"], d1["arrow"]))
    add("")
    add("Generated by `check.sh` (its last step, `results.py`) from the records in `runs/`. Change the")
    add("scripts or the code, never this file. Gas is from real transactions on anvil (Osaka), reference")
    add("sample 0, each result checked against the NumPy reference or the protocol before its gas is")
    add("recorded. %s; whole `check.sh` run: %s s." % (total[2], total[1]))
    add("")
    add("## 1. The second model")
    add("")
    add("| | |")
    add("|---|---|")
    add("| Network | %s, dense, ReLU by clamp to 0..127 |" % d2["arrow"])
    add("| Parameters | %s weights (int8) and %s biases (int32) |" % (n(d2["weights"]), n(d2["biases"])))
    add("| Test accuracy, integer model | %.2f%% (%s of %s MNIST test images) |" % (
        100.0 * m2["accuracy"]["integer"], n(round(m2["accuracy"]["integer"] * m2["accuracy"]["test_samples"])),
        n(m2["accuracy"]["test_samples"])))
    add("| Test accuracy, float model before quantisation | %.2f%% |" % (100.0 * m2["accuracy"]["float"]))
    add("| Training | `train.py`: seed %d, NumPy %s, %d float epochs, post-training quantisation "
        "(no quantisation-aware fine-tuning) |" % (trained["training"]["seed"], trained["training"]["numpy"],
                                                   trained["training"]["float_epochs"]))
    add("| Model root (what the arbiter is deployed with) | `%s` |" % d2["root"])
    add("")
    add("| Layer | Size | Weight fractional bits | Shift | Worst-case accumulator (int32 maximum 2,147,483,647) |")
    add("|---|---|---|---|---|")
    for index, layer in enumerate(m2["layers"], start=1):
        add("| %d | %d -> %d | %d | %s | %s, proved by a `static_assert` in `ingots/model/src/layer%d.fe` |" % (
            index, layer["in"], layer["out"], layer["weight_frac_bits"],
            "none (logits)" if layer["shift"] is None else layer["shift"], n(layer["worst_case_abs_acc"]), index))
    add("")
    add("## 2. Scaling: what grows with the model and what does not")
    add("")
    add("Both columns come from the same two scripts (`tools/arbiter_gas_any.sh`, `tools/network_gas.sh`) in the")
    add("same run. The left column is the hand-written arbiter and `Network` of `ingots/onchain`; its figures")
    add("equal `docs/numbers.md`. The right column is generated code (`tools/gen_arbiter.py`,")
    add("`tools/gen_network.py`). Every figure is measured; none is a projection.")
    add("")
    add("| | %s (shipped) | %s (this example) | Ratio |" % (d1["arrow"], d2["arrow"]))
    add("|---|---|---|---|")

    def row(label, v1, v2, ratio=True):
        if isinstance(v1, int) and isinstance(v2, int):
            add("| %s | %s | %s | %s |" % (label, n(v1), n(v2), "%.2fx" % (v2 / v1) if ratio else ""))
        else:
            add("| %s | %s | %s | |" % (label, v1, v2))

    row("Layers", len(m1["layers"]), len(m2["layers"]), ratio=False)
    row("Parameters (weights and biases)", d1["weights"] + d1["biases"], d2["weights"] + d2["biases"])
    row("Neurons (leaves of the model tree)", d1["neurons"], d2["neurons"])
    row("Merkle proof, nodes", "%d to %d" % d1["proof"], "%d to %d" % d2["proof"])
    row("Whole forward pass on-chain, `Network.classify`, gas", full1, full2)
    row("the same, share of the per-transaction cap (%s)" % n(CAP), pct(full1, CAP), pct(full2, CAP))
    row("`claim`, gas", c1["claim"]["gas_used"], c2["claim"]["gas_used"])
    row("`claim`, calldata bytes", c1["claim"]["calldata_bytes"], c2["claim"]["calldata_bytes"])
    fan = {}
    for which, record in ((0, a1), (1, a2)):
        for layer, fan_in, call in challenges(record):
            fan.setdefault(fan_in, [None, None])[which] = (layer, call)
    for fan_in in sorted(fan, reverse=True):
        cells = []
        for entry in fan[fan_in]:
            cells.append("" if entry is None else "%s (layer %d)" % (n(entry[1]["gas_used"]), entry[0]))
        ratio = ""
        if all(fan[fan_in]):
            ratio = "%.2fx" % (fan[fan_in][1][1]["gas_used"] / fan[fan_in][0][1]["gas_used"])
        add("| Neuron challenge, fan-in %d, gas | %s | %s | %s |" % (fan_in, cells[0], cells[1], ratio))
    for fan_in in sorted(fan, reverse=True):
        cells = ["" if entry is None else n(entry[1]["calldata_bytes"]) for entry in fan[fan_in]]
        add("| the same, calldata bytes, fan-in %d | %s | %s | |" % (fan_in, cells[0], cells[1]))
    first1, first2 = challenges(a1, "")[0][2]["gas_used"], challenges(a2, "")[0][2]["gas_used"]
    row("Layer 1 challenge as the first slash ever (as `docs/numbers.md` reports it), gas", first1, first2)
    row("`challengeClass`, gas", c1["later challengeClass"]["gas_used"], c2["later challengeClass"]["gas_used"])
    row("`finalize`, gas", c1["finalize"]["gas_used"], c2["finalize"]["gas_used"])
    worst1, worst2 = first1, first2
    extra = first2 - challenges(a2)[0][2]["gas_used"]
    honest1 = c1["claim"]["gas_used"] + c1["finalize"]["gas_used"]
    honest2 = c2["claim"]["gas_used"] + c2["finalize"]["gas_used"]
    row("Honest path, `claim` + `finalize`, gas", honest1, honest2)
    row("the same, against one whole forward pass", pct(honest1, full1), pct(honest2, full2))
    row("Dearest dispute against one whole forward pass", pct(worst1, full1), pct(worst2, full2))
    row("`Arbiter` deployed bytes (limit 24,576)", a1["arbiter_runtime_bytes"], a2["arbiter_runtime_bytes"])
    add("")
    add("The neuron and class challenge rows are each challenge's second measurement in the run, when the")
    add("challenger's credit and the contract's `burned` total are already non-zero: the same storage state for")
    add("every layer, so the rows can be compared with each other. The very first slash also turns those two")
    add("slots from zero to non-zero and costs %s gas more; that is the \"first slash ever\" row, and it is the" % n(extra))
    add("dearest a dispute gets.")
    add("")
    add("The `Arbiter` sizes are the deployed code: the runtime `fe build` writes (section 4, and")
    add("`docs/numbers.md` for the shipped model) plus 96 bytes for its three immutable fields.")
    add("")
    add("### What the numbers show")
    add("")
    same = [f for f in fan if all(fan[f])]
    params = (d2["weights"] + d2["biases"]) / (d1["weights"] + d1["biases"])
    for fan_in in same:
        g1, g2 = fan[fan_in][0][1]["gas_used"], fan[fan_in][1][1]["gas_used"]
        add("- **A dispute is priced by the one neuron it re-runs.** The two models have a layer of the same")
        add("  fan-in (%d): challenging one of its neurons costs %s gas in the small model and %s in the large"
            % (fan_in, n(g1), n(g2)))
        add("  one, %+.1f%%, while the large model has %.1f times the parameters and its whole forward pass costs"
            % (100.0 * (g2 - g1) / g1, params))
        add("  %.2f times as much (%s against %s)." % (full2 / full1, n(full2), n(full1)))
        l1, l2 = fan[fan_in][0][0], fan[fan_in][1][0]
        add("  The fan-in is the same, so the kernel does the same number of multiply-adds; the %s gas of"
            % n(g2 - g1))
        add("  difference were not broken down further. What differs: the calldata is %d bytes longer and all of"
            % (fan[fan_in][1][1]["calldata_bytes"] - fan[fan_in][0][1]["calldata_bytes"]))
        add("  it is hashed, because the layer's output vector is %d packed words instead of %d and the proof of the neuron"
            % ((m2["layers"][l2 - 1]["out"] + 31) // 32, (m1["layers"][l1 - 1]["out"] + 31) // 32))
        add("  measured has %d nodes instead of %d. The record also has one more slot to load." % (
            proof_nodes(m2, l2), proof_nodes(m1, l1)))
    by_fan = sorted(((f, fan[f][1][1]["gas_used"]) for f in fan if fan[f][1]), reverse=True)
    if len(by_fan) >= 3:
        (f_a, g_a), (f_b, g_b), (f_c, g_c) = by_fan[0], by_fan[1], by_fan[2]
        add("- **Unflattering: below a few hundred inputs the fan-in hardly matters, because the fixed part of a")
        add("  challenge dominates.** In the large model the challenges cost %s (fan-in %d), %s (%d) and %s (%d)."
            % (n(g_a), f_a, n(g_b), f_b, n(g_c), f_c))
        add("  From %d to %d inputs the cost falls by %s gas, about %.0f per input (arithmetic, calldata and"
            % (f_a, f_b, n(g_a - g_b), (g_a - g_b) / (f_a - f_b)))
        add("  hashing of the row and the input together); from %d to %d it falls by only %s, and the smaller"
            % (f_b, f_c, n(g_b - g_c)))
        add("  one even has more calldata (%s bytes against %s: the last layer's output is %d `int32` words, a"
            % (n(fan[f_c][1][1]["calldata_bytes"]), n(fan[f_b][1][1]["calldata_bytes"]), m2["layers"][-1]["out"]))
        add("  hidden layer's is packed). The cheapest challenge, `challengeClass`, runs no neuron and costs %s:"
            % n(c2["later challengeClass"]["gas_used"]))
        add("  storage, the commitment check and the transaction itself. So a dispute is never much cheaper than")
        add("  that, however small the neuron.")
    dg = c2["claim"]["gas_used"] - c1["claim"]["gas_used"]
    db = c2["claim"]["calldata_bytes"] - c1["claim"]["calldata_bytes"]
    add("- **Unflattering: the claim does grow with the model, by its width and its depth.** `claim` carries")
    add("  every layer's output, so its calldata went from %s to %s bytes (+%d) and its gas from %s to %s"
        % (n(c1["claim"]["calldata_bytes"]), n(c2["claim"]["calldata_bytes"]), db,
           n(c1["claim"]["gas_used"]), n(c2["claim"]["gas_used"])))
    add("  (+%s, %+.1f%%): one more committed vector is one more hash in a fresh storage slot (22,100 gas) plus"
        % (n(dg), 100.0 * dg / c1["claim"]["gas_used"]))
    add("  its calldata and its copy in the `Claimed` event. It grows with the sum of the layer widths, not with")
    add("  the number of weights: %.1f times the parameters cost %.2f times the claim gas."
        % (params, c2["claim"]["gas_used"] / c1["claim"]["gas_used"]))
    add("- **The saving grows with the model.** The honest path (`claim` + `finalize`) is %s of one whole"
        % pct(honest1, full1))
    add("  forward pass for the small model and %s for the large one; the dearest dispute is %s and %s."
        % (pct(honest2, full2), pct(worst1, full1), pct(worst2, full2)))
    add("  In gas, not in shares: the honest path costs %s more for the large model and the dearest dispute"
        % n(honest2 - honest1))
    add("  %s more, against %s more for the whole forward pass." % (n(worst2 - worst1), n(full2 - full1)))
    add("  The whole forward pass of the large model is %s of the per-transaction gas cap, so a network about"
        % pct(full2, CAP))
    add("  twice this size could no longer be run on-chain in one transaction at all, while its claims and")
    add("  disputes would cost about what these do. That last sentence is an inference from the table, not a")
    add("  measurement: no third model was built.")
    add("- **Code size grows by one handler per layer:** the `Arbiter` went from %s to %s bytes."
        % (n(a1["arbiter_runtime_bytes"]), n(a2["arbiter_runtime_bytes"])))
    add("")
    add("## 3. The checks behind this file (`check.sh`, one run)")
    add("")
    add("| Step | Result | Wall time | Last line of its output |")
    add("|---|---|---|---|")
    for status, seconds, name, detail in (row_ for row_ in steps if row_[0] != "total"):
        add("| %s | %s | %s s | %s |" % (name, status, seconds, detail.replace("|", "\\|")))
    add("")
    add("The model ingot's tests are the first %s reference vectors (two tests each: layer by layer, and neuron"
        % total[3])
    add("by neuron through `neuron_from_words`, the function the arbiter calls), on the EVM backend and again")
    add("natively. The native classifier against the NumPy reference on the whole test set:")
    add("")
    add("```")
    out.extend(native)
    add("```")
    add("")
    add("The arbiter's contract tests are generated with the contract (`ingots/arbiter/src/arbiter_tests.fe`):")
    add("an honest claim survives the challenge of every one of its %d neurons and the class challenge, and is"
        % d2["neurons"])
    add("finalised; one false value per layer and a false class are each slashed by their own challenge; wrong")
    add("proofs, substituted vectors and malformed claims are refused, each with its own error.")
    add("")
    add("## 4. Runtime sizes (`fe build`, limit 24,576 bytes)")
    add("")
    add("| Contract | Runtime bytes | Under the limit by |")
    add("|---|---|---|")
    for name, size in sizes.items():
        add("| `%s` | %s | %s |" % (name, n(size), n(24576 - size)))
    add("")
    add("`Rows0` to `Rows%d` hold the %s weights of layer 1 and its biases; `Network` holds the later layers."
        % (len(w2["weight_contract_bytes"]) - 1, n(m2["layers"][0]["in"] * m2["layers"][0]["out"])))
    add("`Wallet` is a test double from the arbiter's tests, `Tally` the consumer example (`ingots/consumer`).")
    add("")
    with open(os.path.join(HERE, "RESULTS.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote RESULTS.md (%d lines)" % len(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
