"""Writes RESULTS.md from the records of one check.sh run (runs/) and the committed records of the
dense address-risk example (../address-risk/runs/). Standard library only. Every number in the file
comes from a record; the words around them are fixed, except where a comparison decides them.

    python3 results.py
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DENSE = os.path.join(HERE, "..", "address-risk")


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def n(v):
    return "{:,}".format(v)


def pct(v):
    return "%.2f%%" % (100 * v)


def ratio(a, b):
    return "%.1f%%" % (100.0 * a / b)


def call(record, prefix):
    for c in record["calls"]:
        if c["call"].startswith(prefix):
            return c
    raise SystemExit("results: no call %r in %s" % (prefix, record.get("model")))


def main():
    model = load(os.path.join(HERE, "out", "model.json"))
    forest = load(os.path.join(HERE, "build", "forest.json"))
    arb = load(os.path.join(HERE, "runs", "arbiter-gas.json"))
    ens = load(os.path.join(HERE, "runs", "ensemble-gas.json"))
    gate = load(os.path.join(HERE, "runs", "gate-gas.json"))
    sizes = load(os.path.join(HERE, "runs", "sizes.json"))
    native = open(os.path.join(HERE, "runs", "native.txt"), encoding="utf-8").read().strip()
    steps = [line.rstrip("\n").split("\t") for line in open(os.path.join(HERE, "runs", "steps.tsv"),
                                                            encoding="utf-8")]
    d_model = load(os.path.join(DENSE, "out", "model.json"))
    d_arb = load(os.path.join(DENSE, "runs", "arbiter-gas.json"))
    d_net = load(os.path.join(DENSE, "runs", "network-gas.json"))
    d_gate = load(os.path.join(DENSE, "runs", "gate-gas.json"))

    total = [s for s in steps if s[0] == "total"][0]
    fe_version = total[2]
    m, dm = model["metrics"], d_model["metrics"]
    tr = model["training"]
    trees, depth = len(model["trees"]), model["depth"]
    nodes, leaves = trees * ((1 << depth) - 1), trees * (1 << depth)
    d_params = sum(l["in"] * l["out"] + l["out"] for l in d_model["layers"])
    d_sizes = " -> ".join([str(d_model["layers"][0]["in"])] + [str(l["out"]) for l in d_model["layers"]])

    claim = call(arb, "claim")
    fin = call(arb, "finalize")
    first_trees = [c for c in arb["calls"] if c["call"].startswith("challengeTree")]
    later_trees = [c for c in arb["calls"] if c["call"].startswith("later challengeTree")]
    first_class = call(arb, "challengeClass")
    later_class = call(arb, "later challengeClass")
    whole = ens["classify"][0]
    honest = claim["gas_used"] + fin["gas_used"]
    dearest = max([c["gas_used"] for c in first_trees] + [first_class["gas_used"]])
    d_claim, d_fin = call(d_arb, "claim"), call(d_arb, "finalize")
    d_whole = d_net["classify"]["gas_used"]
    d_honest = d_claim["gas_used"] + d_fin["gas_used"]
    d_dearest = max(c["gas_used"] for c in d_arb["calls"] if not c["call"].startswith("later")
                    and c["call"].startswith("challenge"))
    d_later = [c for c in d_arb["calls"] if c["call"].startswith("later challengeNeuron")]
    proof_len = len(forest["trees"][0]["proof"])
    per_tree_whole = whole["execution"] / trees

    out = []
    w = out.append
    w("# Results: address risk, a forest of %d trees of depth %d" % (trees, depth))
    w("")
    w("Generated by `check.sh` (its last step, `results.py`) from the records in `runs/`. Change the")
    w("scripts or the code, never this file. Gas is from real transactions on anvil (Osaka), each result")
    w("checked against the pure-Python reference or the protocol before its gas is recorded. %s; whole"
      % fe_version)
    w("`check.sh` run: %s s." % total[1])
    w("")
    w("## 1. The model and how good it is")
    w("")
    w("| | |")
    w("|---|---|")
    w("| Model | %d complete trees of depth %d (gradient boosting, logistic loss), one margin: the score of "
      "class 1 is its base plus the sum of the %d leaf values the input reaches; class 0 scores its base, 0 |"
      % (trees, depth, trees))
    w("| Size | %s split nodes (a feature index and a threshold byte each) and %s leaves (int16, %d fractional bits) |"
      % (n(nodes), n(leaves), model["leaf_frac_bits"]))
    w("| Input | the dense example's 14 bytes per account, the same thresholds (`../address-risk/features.json`) |")
    w("| Rows | the dense example's split: %s training, %s validation, %s test |"
      % (n(tr["rows"]["train"]), n(tr["rows"]["validation"]), n(tr["rows"]["test"])))
    w("| Training | `train.py`: %s, learning rate %s, L2 %s; class weight %s, depth %d and %d trees chosen from "
      "class weights %s, depths %s and %s trees by integer F1 on the validation rows |"
      % (tr["method"], tr["learning_rate"], tr["lambda"], tr["class_weight"], depth, trees,
         ", ".join(str(v) for v in tr["class_weights_tried"]),
         ", ".join(str(v) for v in tr["depths_tried"]),
         ", ".join(str(v) for v in tr["tree_counts_tried"])))
    w("| Model root (what the arbiter is deployed with) | `%s` |" % forest["root"])
    w("")
    w("On the %s test rows, scored once after the choice was made (integer model, the one the contracts"
      % n(m["samples"]))
    w("run), beside the dense network of `examples/address-risk` on the same rows:")
    w("")
    w("| Measure | Forest (this example) | Dense %s | Majority baseline |" % d_sizes)
    w("|---|---|---|---|")
    w("| Accuracy | %s (%s of %s) | %s | %s |" % (pct(m["accuracy"]), n(m["tp"] + m["tn"]), n(m["samples"]),
                                              pct(dm["accuracy"]), pct(m["majority_baseline"])))
    w("| Precision (of the accounts it flags, how many are flagged in the data) | %s (%s of %s) | %s | |"
      % (pct(m["precision"]), n(m["tp"]), n(m["tp"] + m["fp"]), pct(dm["precision"])))
    w("| Recall (of the accounts flagged in the data, how many it flags) | %s (%s of %s) | %s | |"
      % (pct(m["recall"]), n(m["tp"]), n(m["tp"] + m["fn"]), pct(dm["recall"])))
    w("| F1 | %.4f | %.4f | |" % (m["f1"], dm["f1"]))
    w("| Wrong answers | %s | %s | %s |" % (n(m["fp"] + m["fn"]), n(dm["fp"] + dm["fn"]),
                                           n(m["tp"] + m["fn"])))
    w("")
    fl = tr["test"]["float"]
    w("The float forest before quantisation scores the same on the test rows (accuracy %s, F1 %.4f): the"
      % (pct(fl["accuracy"]), fl["f1"]))
    w("int16 leaves lose nothing measurable here. The largest absolute class score any input can reach is")
    w("%s (int32 maximum 2,147,483,647), checked by `static_assert`s in `ingots/model/src/forest.fe`; that"
      % n(model["worst_case_abs_score"]))
    w("no sum of %d int16 leaves and a base can overflow is proved by the type (`trees::sum_fits_i32`)." % trees)
    w("")
    w("## 2. Gas: the forest beside the dense network")
    w("")
    w("The dense column is the committed record of `examples/address-risk/runs/`, not measured again here.")
    w("Every figure is measured. A dispute here re-walks one tree: %d comparisons, and a Merkle proof of %d"
      % (depth, proof_len))
    w("siblings for the tree's %d words." % forest["shape"]["tree_words"])
    w("")
    w("| | Dense %s | Forest %dx%d (this example) |" % (d_sizes, trees, depth))
    w("|---|---|---|")
    w("| Parameters | %s | %s nodes and %s leaves |" % (n(d_params), n(nodes), n(leaves)))
    w("| Test F1 | %.4f | %.4f |" % (dm["f1"], m["f1"]))
    w("| Whole model on-chain, `classify`, gas | %s | %s (`Ensemble` and %d tree holders) |"
      % (n(d_whole), n(whole["gas_used"]), len(ens["holder_bytes"])))
    w("| `claim`, gas | %s | %s |" % (n(d_claim["gas_used"]), n(claim["gas_used"])))
    w("| `claim`, calldata bytes | %s | %s |" % (n(d_claim["calldata_bytes"]), n(claim["calldata_bytes"])))
    w("| `finalize`, gas | %s | %s |" % (n(d_fin["gas_used"]), n(fin["gas_used"])))
    w("| Honest path, `claim` + `finalize`, gas | %s | %s |" % (n(d_honest), n(honest)))
    w("| **Honest path against one whole run** | **%s** | **%s** |"
      % (ratio(d_honest, d_whole), ratio(honest, whole["gas_used"])))
    w("| Dearest dispute (first slash ever), gas | %s | %s |" % (n(d_dearest), n(dearest)))
    w("| **Dearest dispute against one whole run** | **%s** | **%s** |"
      % (ratio(d_dearest, d_whole), ratio(dearest, whole["gas_used"])))
    w("| One unit re-run, later slashes, gas | %s (a neuron, by fan-in) | %s (a tree) |"
      % (", ".join("%s (%s)" % (n(c["gas_used"]), c["call"].split("(")[1].split()[0])
                   for c in d_later),
         ", ".join(n(c["gas_used"]) for c in later_trees)))
    w("| One unit re-run, calldata bytes | %s | %s |"
      % (n(d_later[0]["calldata_bytes"]), n(later_trees[0]["calldata_bytes"])))
    w("| `challengeClass`, first and later, gas | %s, %s | %s, %s |"
      % (n(call(d_arb, "challengeClass")["gas_used"]), n(call(d_arb, "later challengeClass")["gas_used"]),
         n(first_class["gas_used"]), n(later_class["gas_used"])))
    w("| `Arbiter` deployed bytes (limit 24,576) | %s | %s |"
      % (n(d_arb["arbiter_runtime_bytes"]), n(arb["arbiter_runtime_bytes"])))
    w("")
    w("Whole-forest runs measured: %s. \"Later slashes\" are each challenge's second measurement in a run,"
      % "; ".join("sample %d, %s gas (%s of execution)" % (r["sample"], n(r["gas_used"]), n(r["execution"]))
                  for r in ens["classify"]))
    w("when the challenger's credit and the `burned` total are already non-zero.")
    w("")
    w("### What the numbers show")
    w("")
    if honest > whole["gas_used"]:
        w("- **Unflattering: the honest path still costs more than running the forest whole.** One whole")
        w("  run is %s gas; claiming and finalising is %s, %s of it, and the answer arrives only after the"
          % (n(whole["gas_used"]), n(honest), ratio(honest, whole["gas_used"])))
        w("  challenge window. A contract that needs this model's answer now should call `Ensemble`.")
    else:
        w("- **The honest path is cheaper than one whole run.** One whole run is %s gas; claiming and"
          % n(whole["gas_used"]))
        w("  finalising is %s, %s of it. That is the opposite of the dense network on the same data, whose"
          % (n(honest), ratio(honest, whole["gas_used"])))
        w("  honest path costs %s of its whole run: the forest is bigger to run (every tree is loaded and"
          % ratio(d_honest, d_whole))
        w("  walked) while the claim grows only by its committed outputs (%d words). The answer still"
          % forest["shape"]["output_words"])
        w("  arrives only after the challenge window; a contract that needs it at once calls `Ensemble`.")
    w("- **A dispute stays small:** the dearest one costs %s gas, %s of a whole run. Walking one tree"
      % (n(dearest), ratio(dearest, whole["gas_used"])))
    w("  is %d comparisons; the rest of a tree challenge is the fixed cost of a slash (hashing the two"
      % depth)
    w("  committed vectors, the Merkle proof, the storage writes of the settlement).")
    w("- **Per tree, the whole run costs about %s gas of execution** (%s over %d trees, including the"
      % (n(int(round(per_tree_whole))), n(whole["execution"]), trees))
    w("  calls to the holders and the sum). A tree challenge replaces all of that with one walk.")
    if dearest < d_dearest:
        w("- **The dearest tree dispute is cheaper than the dearest neuron dispute of the dense network**")
        w("  (%s against %s gas), although the forest has %s parameters against %s."
          % (n(dearest), n(d_dearest), n(nodes + leaves), n(d_params)))
    else:
        w("- **The dearest tree dispute costs more than the dearest neuron dispute of the dense network**")
        w("  (%s against %s gas): a tree's words and its proof are longer calldata than a 14-input row."
          % (n(dearest), n(d_dearest)))
    w("- **The forest is the better model on these rows** by F1 (%.4f against %.4f) and accuracy (%s"
      % (m["f1"], dm["f1"], pct(m["accuracy"])))
    w("  against %s), as expected for tabular data. It is also %s times the dense network's parameters."
      % (pct(dm["accuracy"]), "%.0f" % ((nodes + leaves) / d_params)))
    w("")
    w("## 3. The use, end to end: `RiskGate` on anvil")
    w("")
    w("`gate_anvil.sh`: an operator claims the forest's answer for two accounts' features (reference samples")
    w("%d, cleared, and %d, flagged), finalises both after the window, and scores the accounts in"
      % (gate["cleared_sample"], gate["flagged_sample"]))
    w("`RiskGate` (`ingots/consumer`, hand-written, %s bytes deployed). The cleared account enters; the"
      % n(gate["gate_deployed_bytes"]))
    w("flagged one and an unscored one are refused. Scoring from an open claim, scoring by anyone but the")
    w("operator, and clearing one account with the claim about another's features all revert; the script")
    w("checks each.")
    w("")
    w("| Call | Forest: gas | Calldata bytes | Dense example: gas |")
    w("|---|---|---|---|")
    for c in gate["calls"]:
        dc = call(d_gate, c["call"])
        w("| %s | %s | %s | %s |" % (c["call"], n(c["gas_used"]), n(c["calldata_bytes"]), n(dc["gas_used"])))
    g = {c["call"]: c["gas_used"] for c in gate["calls"]}
    standing = g["claim (flagged sample)"] + g["finalize (flagged sample)"] + g["score B (flagged)"]
    w("")
    w("So one account's standing costs the operator %s gas (the second claim, its finalize and its score;"
      % n(standing))
    w("the first of each kind in a run costs more because it also sets a storage slot for the first time).")
    w("Calling `Ensemble.classify` instead is %s gas (section 2); a gate built on that call would add its"
      % n(whole["gas_used"]))
    w("own storage write, and was not built or measured here.")
    w("")
    w("## 4. The checks behind this file (`check.sh`, one run)")
    w("")
    w("| Step | Result | Wall time | Last line of its output |")
    w("|---|---|---|---|")
    for s in steps:
        if s[0] == "total":
            continue
        w("| %s | %s | %s s | %s |" % (s[2], s[0], s[1], s[3].replace("|", "/")))
    w("")
    w("The native classifier against the pure-Python reference on the whole test split:")
    w("")
    w("```")
    w(native)
    w("```")
    w("")
    w("The arbiter's contract tests are generated with the contract (`ingots/arbiter/src/arbiter_tests.fe`):")
    w("an honest claim survives the challenge of every one of its %d trees and the class challenge; a wrong"
      % trees)
    w("tree output is slashed by its tree only; a wrong class by the class challenge only; a forged output")
    w("whose class follows from the forged sum (the lie the class challenge cannot see) by its tree only;")
    w("wrong proofs, another tree's words, substituted vectors and malformed claims are refused, each with")
    w("its own error; finalising and withdrawing move the bond. The Foundry fuzz suite and the mutation run")
    w("of the repository cover the dense arbiter, not this one.")
    w("")
    w("## 5. Runtime sizes (`fe build`, limit 24,576 bytes)")
    w("")
    w("| Contract | Runtime bytes | Under the limit by |")
    w("|---|---|---|")
    for name, size in sorted(sizes.items()):
        w("| `%s` | %s | %s |" % (name, n(size), n(24576 - size)))
    w("")
    holders = forest["holders"]
    w("`Trees0` to `Trees%d` hold the trees for the whole-forest run (%s), as code constants: %s bytes of"
      % (len(holders) - 1, ", ".join("%d to %d" % (h["from"], h["to"] - 1) for h in holders),
         n(32 * forest["shape"]["tree_words"] * trees)))
    w("tree words do not fit one contract. `Wallet` and `Visitor` are test doubles from the arbiter's and")
    w("the gate's tests.")
    with open(os.path.join(HERE, "RESULTS.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("results: RESULTS.md written (%d lines)" % len(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
