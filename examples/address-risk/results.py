"""Write RESULTS.md from the records check.sh leaves in runs/. Standard library only.

Usage:  python3 examples/address-risk/results.py      (check.sh runs it last)

Every figure in RESULTS.md is read from a file a script wrote during a run:
    runs/arbiter-gas.json, runs/network-gas.json, runs/gate-gas.json   this model, on anvil
    runs/sizes.json, runs/native.txt, runs/steps.tsv                   sizes, native differential, timings
    out/model.json, model/*.json                                       the model, its metrics, the training record
    ../mnist-784-128-64-10/runs/*.json, ref/out/model.json,
    ../mnist-784-128-64-10/out/model.json                              the two MNIST models, for the table
The MNIST records are the committed ones of that example (its own check.sh wrote them and CI
compares them with a fresh run); they are not measured again here. Nothing is typed in by hand:
the sentences under the tables are templates filled from the same numbers, and the ones that
depend on which way a comparison falls are chosen by the comparison.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
MNIST = os.path.join(ROOT, "examples", "mnist-784-128-64-10")
sys.path.insert(0, os.path.join(ROOT, "tools"))

from gen_tree import commitment  # noqa: E402

CAP = 16777216  # the Osaka limit of one transaction


def load(*parts):
    with open(os.path.join(*parts), "r", encoding="utf-8") as f:
        return json.load(f)


def n(value):
    return "{:,}".format(value)


def pct(part, whole):
    return "%.1f%%" % (100.0 * part / whole)


class Model:
    """One column of the table: a model file, its arbiter record and its network record."""

    def __init__(self, model, arbiter, network):
        self.model = model
        self.sizes = [model["layers"][0]["in"]] + [layer["out"] for layer in model["layers"]]
        self.arrow = " -> ".join(str(v) for v in self.sizes)
        self.weights = sum(layer["in"] * layer["out"] for layer in model["layers"])
        self.biases = sum(self.sizes[1:])
        self.params = self.weights + self.biases
        calls = {call["call"]: call for call in arbiter["calls"]}
        self.claim = calls["claim"]["gas_used"]
        self.claim_bytes = calls["claim"]["calldata_bytes"]
        self.finalize = calls["finalize"]["gas_used"]
        self.class_challenge = calls["later challengeClass"]["gas_used"]
        self.first = []   # (layer, fan-in, gas) of the first measurement of each neuron challenge
        self.later = []   # the same, measured when the credit and `burned` slots are non-zero
        for call in arbiter["calls"]:
            for prefix, into in (("challengeNeuron", self.first), ("later challengeNeuron", self.later)):
                if call["call"].startswith(prefix):
                    layer = int(call["call"][len(prefix):].split(" ")[0])
                    fan_in = int(call["call"].split("(")[1].split(" ")[0])
                    into.append((layer, fan_in, call["gas_used"]))
        self.dearest = max(gas for _, _, gas in self.first)
        self.honest = self.claim + self.finalize
        self.whole = network["classify"]["gas_used"]
        self.arbiter_bytes = arbiter["arbiter_runtime_bytes"]


def main():
    shipped = Model(load(ROOT, "ref", "out", "model.json"),
                    load(MNIST, "runs", "model1-arbiter-gas.json"), load(MNIST, "runs", "model1-network-gas.json"))
    mnist = Model(load(MNIST, "out", "model.json"),
                  load(MNIST, "runs", "arbiter-gas.json"), load(MNIST, "runs", "network-gas.json"))
    model = load(HERE, "out", "model.json")
    this = Model(model, load(HERE, "runs", "arbiter-gas.json"), load(HERE, "runs", "network-gas.json"))
    trained = load(HERE, "model", model["name"] + ".json")["training"]
    gate = load(HERE, "runs", "gate-gas.json")
    sizes = load(HERE, "runs", "sizes.json")
    metrics = model["metrics"]
    tree = commitment(model)
    with open(os.path.join(HERE, "runs", "steps.tsv"), "r", encoding="utf-8") as f:
        steps = [line.rstrip("\n").split("\t") for line in f if line.strip()]
    with open(os.path.join(HERE, "runs", "native.txt"), "r", encoding="utf-8") as f:
        native = [line.rstrip("\n") for line in f if line.strip()]
    total = next(row for row in steps if row[0] == "total")

    out = []
    add = out.append
    add("# Results: address risk, %s" % this.arrow)
    add("")
    add("Generated by `check.sh` (its last step, `results.py`) from the records in `runs/`. Change the")
    add("scripts or the code, never this file. Gas is from real transactions on anvil (Osaka), each result")
    add("checked against the NumPy reference or the protocol before its gas is recorded. %s; whole" % total[2])
    add("`check.sh` run: %s s." % total[1])
    add("")
    add("## 1. The model and how good it is")
    add("")
    add("| | |")
    add("|---|---|")
    add("| Network | %s, dense, ReLU by clamp to 0..127 |" % this.arrow)
    add("| Parameters | %s weights (int8) and %s biases (int32) |" % (n(this.weights), n(this.biases)))
    add("| Input | 14 on-chain features of an Ethereum account, each quantised to 0..127 by the thresholds in "
        "`features.json` |")
    add("| Classes | 0 = not flagged, 1 = flagged as a scam address in the data set |")
    add("| Rows | %s training, %s validation, %s test (`features.py`, fixed seed) |" % (
        n(trained["rows"]["train"]), n(trained["rows"]["validation"]), n(trained["rows"]["test"])))
    add("| Training | `train.py`: seed %d, NumPy %s, %d float epochs, weight %.1f on the flagged class "
        "(chosen from %s by validation F1), post-training quantisation |" % (
            trained["seed"], trained["numpy"], trained["float_epochs"], trained["class_weight"],
            ", ".join("%.1f" % w for w in trained["class_weights_tried"])))
    add("| Model root (what the arbiter is deployed with) | `%s` |" % tree["root"])
    add("")
    add("On the %s test rows, which no choice was made on (integer model, the one the contracts run):"
        % n(metrics["samples"]))
    add("")
    add("| Measure | Integer model | Float model before quantisation |")
    add("|---|---|---|")
    tf = trained["test"]["float"]
    flagged = metrics["tp"] + metrics["fn"]
    add("| Accuracy | %.2f%% (%s of %s) | %.2f%% |" % (
        100 * metrics["accuracy"], n(metrics["tp"] + metrics["tn"]), n(metrics["samples"]), 100 * tf["accuracy"]))
    add("| Majority-class baseline (answer \"not flagged\" every time) | %.2f%% (%s of %s) | |" % (
        100 * metrics["majority_baseline"], n(metrics["samples"] - flagged), n(metrics["samples"])))
    add("| Precision (of the accounts it flags, how many are flagged in the data) | %.2f%% (%s of %s) | %.2f%% |" % (
        100 * metrics["precision"], n(metrics["tp"]), n(metrics["tp"] + metrics["fp"]), 100 * tf["precision"]))
    add("| Recall (of the accounts flagged in the data, how many it flags) | %.2f%% (%s of %s) | %.2f%% |" % (
        100 * metrics["recall"], n(metrics["tp"]), n(flagged), 100 * tf["recall"]))
    add("| F1 | %.4f | %.4f |" % (metrics["f1"], tf["f1"]))
    add("")
    gain = 100 * (metrics["accuracy"] - metrics["majority_baseline"])
    errors_base = metrics["samples"] - (metrics["samples"] - flagged)
    errors_model = metrics["fp"] + metrics["fn"]
    add("Read plainly: the model is %.2f percentage points above answering \"not flagged\" every time (%s"
        % (gain, n(errors_model)))
    add("wrong answers against %s). It misses %s of the %s flagged accounts, and %s of the %s accounts it"
        % (n(errors_base), n(metrics["fn"]), n(flagged), n(metrics["fp"]), n(metrics["tp"] + metrics["fp"])))
    add("flags are not flagged in the data. That is a screening signal, not a verdict. Limits of the data and")
    add("of what the arbiter proves: `README.md`.")
    add("")
    add("| Layer | Size | Weight fractional bits | Shift | Worst-case accumulator (int32 maximum 2,147,483,647) |")
    add("|---|---|---|---|---|")
    for index, layer in enumerate(model["layers"], start=1):
        add("| %d | %d -> %d | %d | %s | %s, proved by a `static_assert` in `ingots/model/src/layer%d.fe` |" % (
            index, layer["in"], layer["out"], layer["weight_frac_bits"],
            "none (logits)" if layer["shift"] is None else layer["shift"], n(layer["worst_case_abs_acc"]), index))
    add("")
    add("## 2. Gas: this model beside the two MNIST models")
    add("")
    add("The right column is this run. The two MNIST columns are the committed records of")
    add("`examples/mnist-784-128-64-10/runs/`, written by the same two scripts (`tools/arbiter_gas_any.sh`,")
    add("`tools/network_gas.sh`); they are not measured again here. Every figure is measured.")
    add("")
    columns = [shipped, mnist, this]
    add("| | %s (shipped) | %s | %s (this example) |" % tuple(m.arrow for m in columns))
    add("|---|---|---|---|")

    def row(label, cell):
        add("| %s | %s |" % (label, " | ".join(cell(m) for m in columns)))

    row("Parameters (weights and biases)", lambda m: n(m.params))
    row("Whole forward pass on-chain, `Network.classify`, gas", lambda m: n(m.whole))
    row("`claim`, gas", lambda m: n(m.claim))
    row("`claim`, calldata bytes", lambda m: n(m.claim_bytes))
    row("`finalize`, gas", lambda m: n(m.finalize))
    row("Honest path, `claim` + `finalize`, gas", lambda m: n(m.honest))
    row("**Honest path against one whole forward pass**", lambda m: "**%s**" % pct(m.honest, m.whole))
    row("Dearest dispute (a layer 1 neuron, first slash ever), gas", lambda m: n(m.dearest))
    row("**Dearest dispute against one whole forward pass**", lambda m: "**%s**" % pct(m.dearest, m.whole))
    row("Neuron challenge by layer (fan-in), later slashes, gas",
        lambda m: ", ".join("%s (%d)" % (n(gas), fan_in) for _, fan_in, gas in m.later))
    row("`challengeClass`, gas", lambda m: n(m.class_challenge))
    row("`Arbiter` deployed bytes (limit 24,576)", lambda m: n(m.arbiter_bytes))
    add("")
    add("\"Later slashes\" are each challenge's second measurement in a run, when the challenger's credit and")
    add("the contract's `burned` total are already non-zero; the first slash ever also turns those two slots")
    add("from zero to non-zero.")
    add("")
    add("### What the numbers show")
    add("")
    if this.honest > this.whole:
        add("- **Unflattering, and the main result: at this size the dispute protocol does not pay.** Running the")
        add("  whole network in one transaction costs %s gas. Claiming an answer and finalising it costs %s,"
            % (n(this.whole), n(this.honest)))
        add("  %s of that, and the answer arrives only after the challenge window. A contract that wants this"
            % pct(this.honest, this.whole))
        add("  model's answer should call the generated `Network` (`ingots/network`, the same kernel, equal to")
        add("  the reference on every check here) and pay %s gas for an answer in the same transaction, with no"
            % n(this.whole))
        add("  operator, bond or watcher to trust.")
    else:
        add("- **At this size the honest path costs %s of one whole run** (%s against %s gas)."
            % (pct(this.honest, this.whole), n(this.honest), n(this.whole)))
    if this.dearest < this.whole:
        add("- **A dispute is still cheaper than a run, but not by much:** the dearest challenge costs %s gas, %s"
            % (n(this.dearest), pct(this.dearest, this.whole)))
        add("  of a whole run (%s and %s for the two MNIST models)."
            % (pct(shipped.dearest, shipped.whole), pct(mnist.dearest, mnist.whole)))
    else:
        add("- **Unflattering: even one dispute costs more than a run:** %s gas against %s."
            % (n(this.dearest), n(this.whole)))
    add("- **Why: the protocol's cost is nearly fixed, the network's is not.** From %s to %s parameters"
        % (n(this.params), n(mnist.params)))
    add("  (%.0f times) the whole run grows from %s to %s gas (%.0f times), while `claim` grows from %s to %s"
        % (mnist.params / this.params, n(this.whole), n(mnist.whole), mnist.whole / this.whole,
           n(this.claim), n(mnist.claim)))
    add("  (%.2f times) and the dearest dispute from %s to %s (%.2f times). A claim is mostly storage: its"
        % (mnist.claim / this.claim, n(this.dearest), n(mnist.dearest), mnist.dearest / this.dearest))
    add("  record takes %d slots for this model and %d for the largest one (four, and one per committed vector)."
        % (5 + len(model["layers"]), 5 + len(mnist.model["layers"])))
    if this.honest > this.whole and shipped.honest < shipped.whole:
        slope = (shipped.whole - this.whole) / (shipped.params - this.params)
        honest_slope = (shipped.honest - this.honest) / (shipped.params - this.params)
        even = this.params + (this.honest - this.whole) / (slope - honest_slope)
        add("- **Where it starts to pay (a projection, not a measurement).** Between this model and the shipped")
        add("  one the whole run grows by about %.0f gas per parameter. A straight line through those two"
            % slope)
        add("  measurements crosses the honest path near %s parameters. No model of that size was built, and"
            % n(int(round(even, -2))))
        add("  the two models differ in more than size (14 inputs against 784), so read it as \"a few thousand")
        add("  parameters\", nothing finer. Below that, run the network; above it, claim and dispute.")
    add("- **What this example is then for.** It shows the pipeline on a model of a kind people do put behind a")
    add("  contract (a tabular risk score), and it gives the honest answer to \"should this one use the")
    add("  arbiter\": no. The arbiter, its tests and the gate are generated and checked here all the same, and")
    add("  the same commands serve a wider risk model, where the table's left columns apply.")
    add("")
    add("## 3. The use, end to end: `RiskGate` on anvil")
    add("")
    add("`gate_anvil.sh`: an operator claims the model's answer for two accounts' features (reference samples")
    add("%d, cleared, and %d, flagged), finalises both after the window, and scores the accounts in"
        % (gate["cleared_sample"], gate["flagged_sample"]))
    add("`RiskGate` (`ingots/consumer`, hand-written, %s bytes deployed). The cleared account enters; the"
        % n(gate["gate_deployed_bytes"]))
    add("flagged one and an unscored one are refused. Scoring from an open claim, scoring by anyone but the")
    add("operator, and clearing one account with the claim about another's features all revert; the script")
    add("checks each.")
    add("")
    add("| Call | Gas | Calldata bytes |")
    add("|---|---|---|")
    for call in gate["calls"]:
        add("| %s | %s | %s |" % (call["call"], n(call["gas_used"]), n(call["calldata_bytes"])))
    add("")
    by = {call["call"]: call["gas_used"] for call in gate["calls"]}
    per_account = by["claim (flagged sample)"] + by["finalize (flagged sample)"] + by["score B (flagged)"]
    add("So one account's standing costs the operator %s gas (the second claim, its finalize and its score;"
        % n(per_account))
    add("the first of each kind in a run costs more because it also sets a storage slot for the first time).")
    add("Calling `Network.classify` instead is %s gas (section 2); a gate built on that call would add its own"
        % n(this.whole))
    add("storage write, and was not built or measured here.")
    add("")
    add("## 4. The checks behind this file (`check.sh`, one run)")
    add("")
    add("| Step | Result | Wall time | Last line of its output |")
    add("|---|---|---|---|")
    for status, seconds, name, detail in (row_ for row_ in steps if row_[0] != "total"):
        add("| %s | %s | %s s | %s |" % (name, status, seconds, detail.replace("|", "\\|")))
    add("")
    add("The model ingot's tests are the first %s reference vectors (two tests each: layer by layer, and neuron"
        % total[3])
    add("by neuron through `neuron_from_words`, the function the arbiter calls), on the EVM backend and again")
    add("natively. The native classifier against the NumPy reference on the whole test split (its \"accuracy\"")
    add("line counts agreement with the data set's labels):")
    add("")
    add("```")
    out.extend(native)
    add("```")
    add("")
    add("The arbiter's contract tests are generated with the contract (`ingots/arbiter/src/arbiter_tests.fe`):")
    add("an honest claim survives the challenge of every one of its %d neurons and the class challenge, and is"
        % this.biases)
    add("finalised; one false value per layer and a false class are each slashed by their own challenge; wrong")
    add("proofs, substituted vectors and malformed claims are refused, each with its own error. A three-layer")
    add("arbiter is covered by these tests and the anvil scripts, not by the Foundry fuzz suite or the mutation")
    add("run, which are tied to the two-layer arbiter (`docs/USAGE.md`, section 6).")
    add("")
    add("## 5. Runtime sizes (`fe build`, limit 24,576 bytes)")
    add("")
    add("| Contract | Runtime bytes | Under the limit by |")
    add("|---|---|---|")
    for name, size in sizes.items():
        add("| `%s` | %s | %s |" % (name, n(size), n(24576 - size)))
    add("")
    add("`Rows0` holds the %s weights of layer 1 and its biases; `Network` holds the later layers. `Wallet` and"
        % n(model["layers"][0]["in"] * model["layers"][0]["out"]))
    add("`Visitor` are test doubles from the arbiter's and the gate's tests.")
    add("")
    with open(os.path.join(HERE, "RESULTS.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote RESULTS.md (%d lines)" % len(out))

    # README.md quotes a few of these figures in prose. They must be the ones just written.
    with open(os.path.join(HERE, "README.md"), "r", encoding="utf-8") as f:
        readme = f.read()
    quoted = ["%.2f%%" % (100 * metrics[key]) for key in ("accuracy", "majority_baseline", "precision", "recall")]
    quoted += [n(this.whole), n(this.honest), n(metrics["samples"]), n(errors_model), n(metrics["fp"]),
               n(metrics["tp"] + metrics["fp"])]
    missing = [text for text in quoted if text not in readme]
    if missing:
        print("README.md does not quote the current figures: %s" % ", ".join(missing))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
