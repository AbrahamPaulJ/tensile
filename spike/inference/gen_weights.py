# Generates <outdir>/weights.fe for a dense layer with deterministic pseudo-random int8 weights,
# plus the integer reference output (same arithmetic as nn/src/lib.fe).
# usage: python gen_weights.py IN OUT SHIFT outdir
import sys, os

IN, OUT, SHIFT, outdir = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3]), sys.argv[4]
# optional flags: "ctpack" also emits WP_CT = pack(W) evaluated by the Fe compiler, "nounpacked" omits W
FLAGS = sys.argv[5:]

state = 0x12345678


def rnd():
    global state
    state = (1664525 * state + 1013904223) & 0xFFFFFFFF
    return state >> 8


W = [[(rnd() % 256) - 128 for _ in range(IN)] for _ in range(OUT)]
B = [(rnd() % 20001) - 10000 for _ in range(OUT)]
X = [rnd() % 128 for _ in range(IN)]


def dense(w, b, x):
    out = []
    for o in range(OUT):
        acc = b[o]
        for i in range(IN):
            acc += w[o][i] * x[i]
        assert -(2**31) <= acc < 2**31
        if acc < 0:
            acc = 0
        acc >>= SHIFT
        if acc > 127:
            acc = 127
        out.append(acc)
    return out


Y = dense(W, B, X)


def arr(v):
    return "[" + ", ".join(str(e) for e in v) + "]"


lines = []
lines.append("// GENERATED by gen_weights.py %d %d %d. Do not edit." % (IN, OUT, SHIFT))
lines.append("pub const IN: usize = %d" % IN)
lines.append("pub const OUT: usize = %d" % OUT)
lines.append("pub const SHIFT: i32 = %d" % SHIFT)
if "nounpacked" not in FLAGS:
    lines.append("pub const W: [[i8; %d]; %d] = [" % (IN, OUT))
    for row in W:
        lines.append("    " + arr(row) + ",")
    lines.append("]")
# Packed form: 32 weights per u256, each stored as (w + 128) in one byte, weight i of a row in
# word i // 32 at bit offset 8 * (i % 32). One byte of contract code per weight.
WPR = (IN + 31) // 32
WP = []
for row in W:
    words = []
    for j in range(WPR):
        v = 0
        for k, wv in enumerate(row[32 * j : 32 * j + 32]):
            v |= (wv + 128) << (8 * k)
        words.append("0x%064x" % v)
    WP.append(words)
lines.append("pub const WP: [[u256; %d]; %d] = [" % (WPR, OUT))
for words in WP:
    lines.append("    [" + ", ".join(words) + "],")
lines.append("]")
# Halves, for the split design (two weight-holder contracts, each under the EIP-170 size limit).
HALF = OUT // 2
lines.append("pub const WPR: usize = %d" % WPR)
lines.append("pub const HALF: usize = %d" % HALF)
for name, part in (("WP_A", WP[:HALF]), ("WP_B", WP[HALF:])):
    lines.append("pub const %s: [[u256; %d]; %d] = [" % (name, WPR, HALF))
    for words in part:
        lines.append("    [" + ", ".join(words) + "],")
    lines.append("]")
lines.append("pub const B_A: [i32; %d] = %s" % (HALF, arr(B[:HALF])))
lines.append("pub const B_B: [i32; %d] = %s" % (HALF, arr(B[HALF:])))
if "ctpack" in FLAGS:
    lines.append("pub const WP_CT: [[u256; %d]; %d] = ingot::pack(W)" % (WPR, OUT))
    lines.append("static_assert(WP_CT[0][0] == WP[0][0])")
    lines.append("static_assert(WP_CT[%d][%d] == WP[%d][%d])" % (OUT - 1, WPR - 1, OUT - 1, WPR - 1))
lines.append("pub const B: [i32; %d] = %s" % (OUT, arr(B)))
lines.append("pub const X: [i8; %d] = %s" % (IN, arr(X)))
lines.append("pub const EXPECTED: [i8; %d] = %s" % (OUT, arr(Y)))
os.makedirs(outdir, exist_ok=True)
with open(os.path.join(outdir, "weights.fe"), "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
with open(os.path.join(outdir, "..", "expected_%dx%d.txt" % (IN, OUT)), "w", newline="\n") as f:
    f.write(" ".join(str(v) for v in Y) + "\n")
# ABI calldata argument for cast: int8[IN] literal
with open(os.path.join(outdir, "..", "x_%dx%d.txt" % (IN, OUT)), "w", newline="\n") as f:
    f.write("[" + ",".join(str(v) for v in X) + "]\n")
print("expected:", " ".join(str(v) for v in Y))
