"""Write docs/sepolia-fee.md from deploy/sepolia-fee.jsonl and deploy/sepolia-fee-budget.json.

Usage:
    python3 tools/sepolia_fee_page.py

The record is kept by tools/sepolia_fee_deploy.sh (the deployment) and by tools/fee_keeper.mjs run
by hand with --record (the first keeper cycles, the planted false claim and its challenge). Every
address, hash and gas figure on the page is read from those two files; the cost per day is computed
from the recorded transactions and labelled as a projection. Standard library only.
"""

import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCAN = "https://sepolia.etherscan.io"
MAINSCAN = "https://etherscan.io"
RPC = "https://ethereum-sepolia-rpc.publicnode.com"

rows = [json.loads(line) for line in open(os.path.join(ROOT, "deploy", "sepolia-fee.jsonl"), encoding="utf-8")]
budget = json.load(open(os.path.join(ROOT, "deploy", "sepolia-fee-budget.json"), encoding="utf-8"))
by = {r["label"]: r for r in rows}
SOURCES = {
    "Rows0": "the weights of layer 1, read by `Network`",
    "Network": "the whole network in one call (`classify`), for read-only cross-checks",
    "Arbiter": "the generated arbiter: claims, challenges, bonds",
    "TickRelay": "the stand-in for the mainnet pool (trust assumption, below)",
    "FeeOracle": "the consumer: builds the input from the relayed ticks, applies final claims",
}
CAP = 50_000_000  # MAX_FEE_WEI of .github/workflows/fee-keeper.yml


def tx(r):
    return "[`%s...`](%s/tx/%s)" % (r["hash"][:14], SCAN, r["hash"])


def gwei(wei):
    return "%g gwei" % (wei / 1e9)


def eth(wei):
    return "%.10f ETH" % (wei / 1e18) if wei < 1e12 else "%.6f ETH" % (wei / 1e18)


out = []
w = out.append
w("# The fee-tier example, live on Sepolia")
w("")
w("Generated by `tools/sepolia_fee_page.py` from `deploy/sepolia-fee.jsonl` (every transaction the")
w("deployment and the hand-run keeper cycles sent) and `deploy/sepolia-fee-budget.json` (the budget read")
w("before deploying). Nothing here is typed by hand. The status page is")
w("[abrahampaulj.github.io/tensile/fee-live/](https://abrahampaulj.github.io/tensile/fee-live/).")
w("")
w("## What runs")
w("")
w("- **The keeper** (`tools/fee_keeper.mjs`, every 10 minutes from `.github/workflows/fee-keeper.yml`)")
w("  reads the tick of the mainnet Uniswap v3 USDC/WETH 0.05% pool at every 50th mainnet block, from")
w("  two public mainnet nodes that must agree, and writes it to `TickRelay` on Sepolia, which hands it")
w("  to `FeeOracle.observe()` in the same call. Every 6 moves (one hour) it runs the 144-32-16-3 network")
w("  on the oracle's newest window and posts the answer to the `Arbiter` with a bond. After the dispute")
w("  window it finalises the claim and applies it to `FeeOracle`, whose `fee()` then returns the tier's fee.")
w("- **The watcher** is in the same keeper run (it challenges any false claim it finds, anyone's) and,")
w("  without a key, in `demo/test/tensile-fee-live.mjs` (hourly in the same workflow) and in the status")
w("  page, which re-reads every relayed tick from mainnet and re-runs every claim in the browser.")
w("")
w("## Trust assumption: the relay")
w("")
w("Sepolia has no pool that trades at mainnet prices. On Sepolia `FeeOracle` therefore reads")
w("`TickRelay`, and **the relay holds whatever tick the keeper wrote**: nothing on Sepolia can check it")
w("against mainnet. What makes the trust checkable:")
w("")
w("- the relay accepts ticks only on one grid of mainnet blocks: tick `n` is of block `firstBlock() + 50 n`,")
w("  with no gap and no repeat, the first block a multiple of 50 (the grid of `examples/amm-fee/data/ticks.csv`);")
w("- every tick is emitted with its mainnet block (`Relayed(number, block, tick, moves)`), so anyone can read")
w("  the pool's `slot0()` at that block and compare: the watcher does it for every tick, every hour, and so")
w("  does the status page on every visit;")
w("- the relay answers `slot0()` only inside its own `relay` call, which calls `observe()` once per tick, so")
w("  the oracle cannot store a tick twice or one that was not relayed.")
w("")
w("On mainnet there would be no relay: the oracle reads the pool itself (`examples/amm-fee/fork_check.sh`")
w("did that once on a fork). The other trust assumptions are the example's own: one honest watcher awake")
w("inside every dispute window, and a spot tick as input (one trade in the observed block moves it).")
w("")
w("**Sepolia-specific deployment choice.** `FeeOracle` is deployed with an interval of 0 blocks: its")
w("clock is the relay's grid of mainnet blocks, not Sepolia's blocks. A keeper run that is late, or a")
w("skipped run, is caught up by the next run, which relays the missed ticks, each read at its own mainnet")
w("block, so the moves stay 50 mainnet blocks apart as in the training data. That catch-up is visible on")
w("chain: the Sepolia block of a `Relayed` event comes later after its mainnet block than usual. The first")
w("window was filled the same way at the start (below).")
w("")
w("## Contracts")
w("")
w("All are `fe build` output (%s), deployed unchanged. `bash tools/check_deployed_fee.sh` fetches the" % by["Arbiter"].get("fe", "Fe 26.5.1"))
w("code at each address and compares it with a fresh build, byte for byte, constructor words included.")
w("")
w("| Contract | Address | Deployment | Gas used | Source | |")
w("|---|---|---|---|---|---|")
for label in ("Arbiter", "TickRelay", "FeeOracle", "Network", "Rows0"):
    r = by[label]
    w("| `%s` | [`%s`](%s/address/%s) | %s | %s | `%s` | %s |" % (
        label, r["address"], SCAN, r["address"], tx(r), "{:,}".format(r["gasUsed"]), r.get("source", ""), SOURCES[label]))
if "setOracle" in by:
    w("| `setOracle` | | %s | %s | | the relay is told the oracle, once |" % (tx(by["setOracle"]), "{:,}".format(by["setOracle"]["gasUsed"])))
a = by["Arbiter"]
w("")
w("The arbiter was deployed with the model root `%s`, a bond of %g ETH and a dispute window of %d minutes." % (
    a["root"], int(a["bond"]) / 1e18, int(a["window"]) // 60))
w("`FeeOracle` reads the relay `%s` with an interval of 0 blocks; the relay's keeper is `%s`." % (
    by["FeeOracle"]["pool"], by["TickRelay"]["keeper"]))
w("")

# The budget.
creations = sum(by[n]["gasUsed"] for n in ("Rows0", "Network", "Arbiter", "TickRelay", "FeeOracle"))
w("## Budget")
w("")
w("Read before deploying (%s, Sepolia block %s): balance %s, gas price %d wei (base fee %d wei)." % (
    budget["measured"], "{:,}".format(budget["block"]), eth(budget["balance_wei"]), budget["gas_price_wei"], budget["base_fee_wei"]))
w("")
w("| Creation | `eth_estimateGas` before | Gas used |")
w("|---|---|---|")
for name, est in budget["creations"].items():
    w("| `%s` | %s | %s |" % (name, "{:,}".format(est), "{:,}".format(by[name]["gasUsed"])))
w("| total | %s | %s |" % ("{:,}".format(budget["creations_total"]), "{:,}".format(creations)))
w("")


def mean(values):
    return sum(values) / len(values) if values else None


keeper = [r for r in rows if r.get("label", "").startswith(("relay ticks", "claim window", "finalize claim", "apply claim", "withdraw", "challenge claim"))]
relay_rows = [r for r in keeper if r["label"].startswith("relay ticks")]
single = [r["gasUsed"] for r in relay_rows if r.get("count") == "1"]
per_tick_batch = mean([r["gasUsed"] / int(r["count"]) for r in relay_rows if int(r.get("count", 0)) >= 2])
claim_gas = mean([r["gasUsed"] for r in keeper if r["label"].startswith("claim window")])
finalize_gas = mean([r["gasUsed"] for r in keeper if r["label"].startswith("finalize claim")])
apply_gas = mean([r["gasUsed"] for r in keeper if r["label"].startswith("apply claim")])
withdraw_gas = mean([r["gasUsed"] for r in keeper if r["label"].startswith("withdraw")])
relay_one = max(single) if single else None
if None not in (claim_gas, finalize_gas, apply_gas, withdraw_gas) and (relay_one or per_tick_batch):
    tick_tx = relay_one if relay_one else per_tick_batch + 21000
    day = 144 * tick_tx + 24 * (claim_gas + finalize_gas + apply_gas + withdraw_gas)
    price = budget["gas_price_wei"]
    spare = budget["balance_wei"] - creations * price - 3 * int(a["bond"])
    w("Running cost, a projection from the transactions recorded below (Glamsterdam gas on Sepolia): 144")
    w("ticks a day relayed one per run (%s gas a run, %s), and 24 claims a day, each with its finalize," % (
        "{:,.0f}".format(tick_tx), "the largest single-tick relay recorded" if relay_one else "measured per tick in batches, plus 21,000"))
    w("apply and withdraw (%s, %s, %s and %s gas, means of the recorded ones): **%s gas a day**." % (
        "{:,.0f}".format(claim_gas), "{:,.0f}".format(finalize_gas), "{:,.0f}".format(apply_gas), "{:,.0f}".format(withdraw_gas), "{:,.0f}".format(day)))
    w("")
    w("| Gas price | Cost a day | Days the balance covers after deployment and three bonds in flight |")
    w("|---|---|---|")
    for label_price, p in (("%d wei (the price read before deploying)" % price, price), ("%s (the keeper's cap, MAX_FEE_WEI)" % gwei(CAP), CAP)):
        w("| %s | %s | %s |" % (label_price, eth(day * p), "{:,.0f}".format(spare / (day * p))))
    w("")
    w("Bonds are not spent: each comes back as a credit when its claim is final, and the keeper withdraws it.")
    w("The keeper sends nothing while the base fee is above the cap, and the gas limits of one run add up")
    w("to at most 6,000,000 (GAS_BUDGET).")
    w("")

# The start and the first cycles.
w("## Transactions sent by hand")
w("")
w("The first keeper cycles were run by hand (`node tools/fee_keeper.mjs --record`), and so was the planted")
w("false claim. Every transaction of those runs:")
w("")
w("| Step | Transaction | Gas used on Sepolia |")
w("|---|---|---|")
for r in rows:
    if r["label"] in SOURCES or r["label"] == "setOracle":
        continue
    what = r["label"]
    if what.startswith("planted false claim"):
        what = "**%s**, posted by a second account `%s`: %s, about the window ending at move %s, with `%s` changed" % (
            what, r["claimant"], r["role"], r["end"], r["posted"])
    elif what.startswith("challenge claim"):
        what = "**%s** by the keeper's watcher step: %s" % (what, r.get("finding", ""))
    w("| %s | %s | %s |" % (what, tx(r), "{:,}".format(r["gasUsed"])))
w("")
first = [r for r in rows if r["label"].startswith("relay ticks")]
if first:
    m = re.search(r"mainnet blocks (\d+)", first[0]["label"])
    if m:
        w("The grid starts at mainnet block [%s](%s/block/%s): the keeper's first run relayed the 145 ticks of" % (
            "{:,}".format(int(m.group(1))), MAINSCAN, m.group(1)))
        w("the 24 hours before it, so the first window was complete at once. Those ticks were read after the")
        w("fact, each at its own block, and the watcher checks them like every other.")
        w("")
w("## Check it yourself")
w("")
w("```")
w("bash tools/check_deployed_fee.sh                  # the bytecode at each address is fe build's")
w("node demo/test/tensile-fee-live.mjs              # every relayed tick against mainnet, every claim re-run")
w("cast call --rpc-url %s %s \"fee()(uint32)\"" % (RPC, by["FeeOracle"]["address"]))
w("cast call --rpc-url %s %s \"latest()(uint256,int32)\"" % (RPC, by["TickRelay"]["address"]))
w("cast call --rpc-url https://eth.drpc.org --block <that block> 0x88e6A0c2dDD26FEEb64F039a2c41296FcB3f5640 \"slot0()(uint160,int24,uint16,uint16,uint16,uint8,bool)\"")
w("```")
w("")
w("The last two print the relay's newest tick with its mainnet block, and the pool's tick at that block on")
w("mainnet: they must be equal.")
open(os.path.join(ROOT, "docs", "sepolia-fee.md"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("docs/sepolia-fee.md: %d recorded transactions" % len(rows))
