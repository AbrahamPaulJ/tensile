"""Turns the reports of tools/m4_numbers.sh into docs/numbers.md and demo/generated/numbers.json.

usage: python3 tools/m4_numbers.py WORK RAW_SIZE INLINE_SIZE TWIN_SIZE FE_VERSION FORGE_VERSION SECONDS
Generated file: change this script or the measurements, never the output.
"""

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def report(path):
    table = {}
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            # Label, then four columns: estimate gasUsed execution frame, then bytes and `ok`.
            m = re.match(r"^(.+?)\s+(\d+)\s+(\d+)\s+(\d+|floor)\s+(\d+)\s+(\d+)\s+ok", line)
            if m:
                table[m.group(1).strip()] = {
                    "used": int(m.group(3)),
                    "execution": None if m.group(4) == "floor" else int(m.group(4)),
                    "frame": int(m.group(5)),
                    "bytes": int(m.group(6)),
                }
    return table


def arbiter(path):
    table = {}
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            m = re.match(r"^(.+?)\s+(\d+)\s+(\d+)\s+(\d+)\s+(\d+) bytes of calldata", line)
            if m:
                table[m.group(1).strip()] = {"used": int(m.group(3)), "execution": int(m.group(4))}
            m = re.search(r"runtime (\d+) bytes", line)
            if m:
                table["runtime"] = int(m.group(1))
    return table


def sizes(path):
    out = {}
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            m = re.match(r"^ok\s+(\w+)\s+(\d+) bytes", line)
            if m:
                out[m.group(1)] = int(m.group(2))
    return out


def n(value):
    return "n/a" if value is None else format(value, ",")


def ratio(a, b):
    return "%.2fx" % (a / b)


def delta(a, b):
    """`a` against the baseline `b`, with a sign."""
    difference = a - b
    return "%s (%+.1f%%)" % (format(difference, "+,"), 100 * difference / b)


def main():
    work, raw_size, inline_size, twin_size, fe_version, forge_version, seconds = sys.argv[1:8]
    raw_size, inline_size, twin_size = int(raw_size), int(inline_size), int(twin_size)
    typed = report(os.path.join(work, "report-typed.txt"))
    raw = report(os.path.join(work, "report-raw.txt"))
    arb = arbiter(os.path.join(work, "arbiter-typed.txt"))
    inline = arbiter(os.path.join(work, "arbiter-inline.txt"))
    twin = arbiter(os.path.join(work, "arbiter-twin.txt"))
    size = sizes(os.path.join(work, "sizes.txt"))

    fe_n1, fe_n2 = typed["NeuronCheck.neuron1 (Fe)"], typed["NeuronCheck.neuron2 (Fe)"]
    raw_n1, raw_n2 = raw["NeuronCheck.neuron1 (Fe)"], raw["NeuronCheck.neuron2 (Fe)"]
    sol_loop, sol_best = typed["NeuronTwin.neuron1 (Sol)"], typed["NeuronTwin.neuron1Unrolled"]
    sol2_best = typed["NeuronTwin.neuron2Unrolled"]
    classify, trace = typed["Network.classify"], typed["Network.trace"]
    calls = [
        ("claim", "claim (honest, sample 0)"),
        ("challengeNeuron1 (784 inputs)", "challengeNeuron1 (layer 1, j=0)"),
        ("challengeNeuron2 (32 inputs)", "challengeNeuron2 (layer 2, j=0)"),
        ("challengeClass", "challengeClass"),
        ("finalize", "finalize (after the window)"),
        ("withdraw (4 credits)", "withdraw (4 credits)"),
    ]
    claim_gas = arb[calls[0][1]]["used"]
    n1_gas = arb[calls[1][1]]["used"]

    out = []
    w = out.append
    w("# Numbers")
    w("")
    w("Generated by `tools/m4_numbers.sh`, the one command behind every gas and size figure this project")
    w("quotes. Change the script or the code, never this file. Real transactions on anvil (Osaka),")
    w("reference sample 0, each result checked against the NumPy reference or the protocol before its gas")
    w("is recorded. The demo page's chain reproduces the Fe figures of sections 1 and 2 exactly")
    w("(`demo/test/run.mjs` compares them).")
    w("")
    w("%s; %s; solc 0.8.38, via-IR, optimiser 200 runs. Whole script: %s s." % (fe_version, forge_version, seconds))
    w("")
    w("## 1. What the dispute saves")
    w("")
    w("| Call | Gas | Against one full `classify` |")
    w("|---|---|---|")
    w("| `Network.classify` (whole network, one transaction) | %s | 100%% |" % n(classify["used"]))
    w("| `Network.trace` (the same, returning every value) | %s | %.1f%% |" % (n(trace["used"]), 100 * trace["used"] / classify["used"]))
    for label, key in calls:
        w("| `%s` | %s | %.1f%% |" % (label, n(arb[key]["used"]), 100 * arb[key]["used"] / classify["used"]))
    w("")
    w("An honest claim costs `claim` + `finalize`, %s gas; a dispute at layer 1, the worst case, costs" % n(claim_gas + arb[calls[4][1]]["used"]))
    w("%s gas once. `classify` is %.1f%% of the Osaka per-transaction cap of 16,777,216 gas." % (n(n1_gas), 100 * classify["used"] / 16777216))
    w("")
    w("## 2. What the abstractions cost at run time")
    w("")
    w("Each row compares the real code with a scratch variant that has the abstraction removed and the")
    w("same behaviour: same checks in the same order, same results (the anvil scripts check them).")
    w("")
    w("| Abstraction removed | Measured on | With it | Without it | Cost of the abstraction |")
    w("|---|---|---|---|---|")
    w("| Typed vectors, scales and shapes: `Packed`, `Row`, `Activations`, `Q` (`tests/abstraction/neuron_check_raw.fe`) | layer 1 neuron, execution gas | %s | %s | %s |" % (
        n(fe_n1["frame"]), n(raw_n1["frame"]), delta(fe_n1["frame"], raw_n1["frame"])))
    w("| the same | layer 2 neuron, execution gas | %s | %s | %s |" % (
        n(fe_n2["frame"]), n(raw_n2["frame"]), delta(fe_n2["frame"], raw_n2["frame"])))
    w("| the same | `NeuronCheck` runtime bytes | %s | %s | %s |" % (
        n(fe_n1["bytes"]), n(raw_n1["bytes"]), delta(fe_n1["bytes"], raw_n1["bytes"])))
    for label, key in calls[1:5]:
        w("| Pure state machine `dispute::step` (`tests/abstraction/inline_settle.py`) | `%s`, gas | %s | %s | %s |" % (
            label, n(arb[key]["used"]), n(inline[key]["used"]), delta(arb[key]["used"], inline[key]["used"])))
    w("| the same | `Arbiter` runtime bytes | %s | %s | %s |" % (
        n(size["Arbiter"]), n(inline_size), delta(size["Arbiter"], inline_size)))
    w("")
    w("Compile-time checks have no run-time cost by construction: the 14 compile-fail cases, the")
    w("`static_assert` overflow proof and the deadline rules in `ingots/dispute/src/step.fe` produce no code.")
    w("")
    w("## 3. Against hand-written Solidity")
    w("")
    w("One neuron, same calldata, same validation (`evm/src/NeuronTwin.sol`, fuzzed against the spec):")
    w("")
    w("| Contract | Layer 1 neuron, transaction | Execution | Layer 2 neuron, execution | Runtime bytes |")
    w("|---|---|---|---|---|")
    w("| Fe, as shipped | %s | %s | %s | %s |" % (n(fe_n1["used"]), n(fe_n1["frame"]), n(fe_n2["frame"]), n(fe_n1["bytes"])))
    w("| Solidity, assembly loop | %s | %s | %s | %s |" % (n(sol_loop["used"]), n(sol_loop["frame"]), n(typed["NeuronTwin.neuron2 (Sol)"]["frame"]), n(sol_loop["bytes"])))
    w("| Solidity, 32 lanes written out, the best found | %s | %s | %s | %s |" % (n(sol_best["used"]), n(sol_best["frame"]), n(sol2_best["frame"]), n(sol_best["bytes"])))
    w("")
    w("Fe against the best Solidity on a layer 1 neuron: %s per transaction, %s of execution." % (
        ratio(fe_n1["used"], sol_best["used"]), ratio(fe_n1["frame"], sol_best["frame"])))
    w("Fe against the Solidity loop: %s per transaction." % ratio(fe_n1["used"], sol_loop["used"]))
    w("")
    w("The whole arbiter (`evm/src/ArbiterTwin.sol`, which passes the same Foundry suite as the Fe")
    w("contract, `tools/m4_twin_suite.sh`):")
    w("")
    w("| Call | Fe | Solidity twin | Fe against Solidity |")
    w("|---|---|---|---|")
    for label, key in calls:
        w("| `%s` | %s | %s | %s |" % (label, n(arb[key]["used"]), n(twin[key]["used"]), ratio(arb[key]["used"], twin[key]["used"])))
    w("| Runtime bytes | %s | %s | %s |" % (n(size["Arbiter"]), n(twin_size), ratio(size["Arbiter"], twin_size)))
    w("")
    w("Much of the `claim` and `finalize` gap is storage layout, which the twin is free to pack: Fe gives")
    w("an `Address` a whole word and the record takes seven slots (`docs/fe-notes.md` M3.6), the twin five.")
    w("")
    w("## 4. Runtime sizes")
    w("")
    w("| Contract | Runtime bytes | Under the 24,576 limit by |")
    w("|---|---|---|")
    for name in ["Arbiter", "Network", "NeuronCheck", "RowsLow", "RowsHigh"]:
        w("| `%s` | %s | %s |" % (name, n(size[name]), n(24576 - size[name])))

    forms = os.path.join(work, "forms.txt")
    if os.path.exists(forms):
        w("")
        w("## 5. Forms of the kernel's inner loop (`tools/kernel_forms.sh`)")
        w("")
        w("Each form is the same dot product, run through both backends and checked against the reference.")
        w("`gas()` is measured inside the EVM with no call around it. Native time is the classifier on all")
        w("10,000 samples at `-O 1`; it varies by about 0.1 s between runs.")
        w("")
        w("| Form | gas() | per multiply-add | Transaction | Runtime bytes | Native, 10,000 samples |")
        w("|---|---|---|---|---|---|")
        with open(forms, "r", encoding="utf-8") as f:
            for line in f:
                m = re.match(r"^(\w+)\s+ok\s+(\d+)\s+([\d.]+)\s+(\d+)\s+(\d+)\s+(.+)$", line.strip())
                if m:
                    name = "**kept: `u32` limbs**" if m.group(1) == "kept" else "`%s`" % m.group(1)
                    w("| %s | %s | %s | %s | %s | %s |" % (name, n(int(m.group(2))), m.group(3), n(int(m.group(4))), n(int(m.group(5))), m.group(6)))

    path = os.path.join(ROOT, "docs", "numbers.md")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")

    page = {
        "classify": classify["used"],
        "neuron_fe": fe_n1["used"],
        "neuron_sol_best": sol_best["used"],
        "neuron_sol_loop": sol_loop["used"],
        "typed_exec": fe_n1["frame"],
        "raw_exec": raw_n1["frame"],
        "step_finalize": arb[calls[4][1]]["used"],
        "inline_finalize": inline[calls[4][1]]["used"],
        "calls": {label: {"fe": arb[key]["used"], "sol": twin[key]["used"]} for label, key in calls},
        "arbiter_bytes": {"fe": size["Arbiter"], "sol": twin_size},
    }
    target = os.path.join(ROOT, "demo", "generated", "numbers.json")
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        json.dump(page, f, indent=1)
        f.write("\n")
    print("wrote docs/numbers.md and demo/generated/numbers.json in %s s" % seconds)
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
