"""Write docs/sepolia.md from deploy/sepolia.jsonl, the record tools/sepolia_run.sh keeps.

Usage:
    python3 tools/sepolia_page.py

Every address, hash and gas figure on the page is read from the record; the local-chain column is
read from demo/generated/numbers.json (written by tools/m4_numbers.sh). Standard library only.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCAN = "https://sepolia.etherscan.io"

rows = [json.loads(line) for line in open(os.path.join(ROOT, "deploy", "sepolia.jsonl"))]
by = {r["label"]: r for r in rows}
local = json.load(open(os.path.join(ROOT, "demo", "generated", "numbers.json")))["calls"]
LOCAL = {
    "claim honest": local["claim"]["fe"],
    "challengeNeuron1": local["challengeNeuron1 (784 inputs)"]["fe"],
    "challengeNeuron2": local["challengeNeuron2 (32 inputs)"]["fe"],
    "challengeClass": local["challengeClass"]["fe"],
    "finalize": local["finalize"]["fe"],
    "withdraw": local["withdraw (4 credits)"]["fe"],
}
WHAT = {
    "claim honest": "Claim 0: the true answer for reference sample 0, with a bond",
    "claim false hidden": "Claim 1: the same, with hidden neuron 0 changed by one",
    "claim false output": "Claim 2: the same, with output 0 changed by one",
    "claim false class": "Claim 3: the same, with the wrong class",
    "challengeNeuron1": "Claim 1 slashed: the contract re-runs hidden neuron 0 (784 inputs)",
    "challengeNeuron2": "Claim 2 slashed: the contract re-runs output neuron 0 (32 inputs)",
    "challengeClass": "Claim 3 slashed: the contract takes the argmax of the committed outputs",
    "finalize": "Claim 0 becomes final after the window; `result(0)` is the answer",
    "withdraw": "The one account withdraws: its returned bond and half of each slashed bond",
}


def tx(label):
    r = by[label]
    return "[`%s...`](%s/tx/%s)" % (r["hash"][:14], SCAN, r["hash"])


out = []
w = out.append
w("# Tensile on Sepolia")
w("")
w("Generated by `tools/sepolia_page.py` from `deploy/sepolia.jsonl`, the record `tools/sepolia_run.sh`")
w("keeps of every transaction it sends. Nothing here is typed by hand.")
w("")
w("The contracts are the output of `fe build` (Fe 26.5.1, `-O 1`), deployed unchanged.")
w("`bash tools/check_deployed.sh` fetches the code at each address from a public node and compares it")
w("with a fresh build, byte for byte.")
w("")
w("| Contract | Address | Deployment |")
w("|---|---|---|")
for label in ("Arbiter", "Network", "RowsLow", "RowsHigh"):
    r = by[label]
    w("| `%s` | [`%s`](%s/address/%s) | %s |" % (label, r["address"], SCAN, r["address"], tx(label)))
w("")
w("The arbiter holds no weights: it was deployed with the model's Merkle root, a bond of 0.001 ETH and")
w("a window of 10 minutes. `Network` runs the whole model, for reference; the demo page calls its")
w("`classify` read-only.")
w("")
w("## The dispute, transaction by transaction")
w("")
w("One account plays both sides, so the figures are the protocol's and the money goes in a circle.")
w("")
w("| Step | Transaction | Gas used on Sepolia | Gas used on anvil (Osaka) |")
w("|---|---|---|---|")
for label in ("claim honest", "claim false hidden", "claim false output", "claim false class",
              "challengeNeuron1", "challengeNeuron2", "challengeClass", "finalize", "withdraw"):
    if label not in by:
        continue
    anvil = "{:,}".format(LOCAL[label]) if label in LOCAL else ""
    w("| %s | %s | %s | %s |" % (WHAT[label], tx(label), "{:,}".format(by[label]["gasUsed"]), anvil))
w("")
w("The two gas columns differ because the two chains do not charge the same. Every figure elsewhere in")
w("this repository is measured on anvil at the Osaka fork, the rules of mainnet today (`docs/numbers.md`).")
w("Sepolia has run the next fork, Glamsterdam, since 2026-10-06, and it charges more for creating state")
w("(EIP-8037) and for reaching it (EIP-8038): a claim writes seven new storage slots, so it is the call")
w("that grows most. The contract and the calls are the same.")
if "estimate classify" in by:
    full = by["estimate classify"]["gasUsed"]
    worst = by["challengeNeuron1"]["gasUsed"]
    w("")
    w("Under those rules the node estimates `Network.classify`, the whole network in one transaction, at")
    w("{:,} gas (an estimate from `eth_estimateGas`, not a mined transaction), so the costliest".format(full))
    w("challenge is {:.1f}% of a full run there, against 9.4% on Osaka.".format(100.0 * worst / full))
w("")
w("After the last step the arbiter holds exactly the burned half of three bonds, 0.0015 ETH, which")
w("`burned()` reports and nothing can withdraw.")
w("")
w("## Check it yourself")
w("")
w("```")
arb = by["Arbiter"]["address"]
w("cast call --rpc-url https://ethereum-sepolia-rpc.publicnode.com %s \"result(uint256)(uint8)\" 0" % arb)
w("cast call --rpc-url https://ethereum-sepolia-rpc.publicnode.com %s \"claimInfo(uint256)(address,uint256,uint256,uint8,uint8)\" 1" % arb)
w("bash tools/check_deployed.sh")
w("```")
w("")
w("The first prints the finalised answer, 7. The second ends in the claim's status: 2 is slashed, 3 is")
w("final. To repeat the whole run with your own key: `SEPOLIA_KEY_FILE=<file> bash tools/sepolia_run.sh`")
w("after removing `deploy/sepolia.jsonl`.")
OPEN = os.path.join(ROOT, "deploy", "sepolia-open.jsonl")
if os.path.exists(OPEN):
    opened = [json.loads(line) for line in open(OPEN)]
    second = next(r for r in opened if r["label"] == "Arbiter")
    POSTED = {"honest": "honest", "hidden": "hidden neuron %s changed by one", "logit": "output %s changed by one",
              "class": "wrong class"}
    w("")
    w("## Open claims: be the watcher")
    w("")
    w("A second arbiter, [`%s`](%s/address/%s), has a bond of %g ETH and a window of %d days, and holds"
      % (second["address"], SCAN, second["address"], int(second["bond"]) / 1e18, int(second["window"]) // 86400))
    w("claims about reference samples 1 to 12 that nobody has challenged. Some are false, on purpose.")
    w("[The watcher page](https://abrahampaulj.github.io/tensile/sepolia/) reads each one from the chain,")
    w("re-runs the network in the browser with the WebAssembly build of the kernel, names the wrong value,")
    w("and asks a public node whether the arbiter would accept the challenge. `node demo/test/sepolia.mjs`")
    w("does the same from the command line, and a scheduled workflow runs it every six hours. Anyone who")
    w("sends a challenge is credited half the bond.")
    w("")
    w("| Claim | Transaction | As posted |")
    w("|---|---|---|")
    for r in opened:
        if not r["label"].startswith("claim "):
            continue
        kind, _, j = r["posted"].partition(":")
        posted = POSTED[kind] % j if "%s" in POSTED[kind] else POSTED[kind]
        w("| %s | [`%s...`](%s/tx/%s) | sample %s, %s |" % (r["id"], r["hash"][:14], SCAN, r["hash"], r["sample"], posted))
open(os.path.join(ROOT, "docs", "sepolia.md"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("docs/sepolia.md: %d recorded transactions" % len(rows))
