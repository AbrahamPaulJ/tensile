"""Flatten the `tensile` and `model` ingots into one standalone Fe file for the WebAssembly target.

`fe build --backend wasm` accepts only a standalone `.fe` file, not an ingot. This writes
`wasm/tensile_wasm.fe`: each ingot becomes an inline `mod`, each of its source files a nested
`mod`, and the paths that name an ingot are rewritten (`ingot::x` inside `tensile` becomes
`ingot::tensile::x`, `tensile::x` inside `model` becomes `ingot::tensile::x`). The Fe source is
otherwise copied byte for byte, so the module runs the same kernel and the same weights as the
contract and the native classifier. `wasm/entry.fe` (hand-written) is appended: the exports.

    python tools/gen_wasm.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INGOTS = os.path.join(ROOT, "ingots")
OUT = os.path.join(ROOT, "wasm", "tensile_wasm.fe")
ENTRY = os.path.join(ROOT, "wasm", "entry.fe")

# Ingot name -> the other ingots it may name by bare path.
ORDER = [("tensile", []), ("model", ["tensile"])]


def rewrite(text, ingot, deps):
    # Inner doc comments are only valid at the top of a file; inside an inline mod make them plain.
    text = re.sub(r"(?m)^(\s*)//!", r"\1//", text)
    # `ingot::` (this ingot's root) -> `ingot::<ingot>::`
    text = re.sub(r"\bingot::", "ingot::%s::" % ingot, text)
    # A dependency named at the start of a path -> `ingot::<dep>::` (not after `::` or a word char).
    for dep in deps:
        text = re.sub(r"(?<![\w:])%s::" % dep, "ingot::%s::" % dep, text)
    return text


def indent(text, n):
    pad = " " * n
    return "".join((pad + line) if line.strip() else line for line in text.splitlines(True))


def ingot_module(ingot, deps):
    src = os.path.join(INGOTS, ingot, "src")
    files = sorted(f for f in os.listdir(src) if f.endswith(".fe"))
    lib = rewrite(open(os.path.join(src, "lib.fe"), encoding="utf-8").read(), ingot, deps)
    parts = [lib.rstrip() + "\n"]
    for f in files:
        if f == "lib.fe":
            continue
        body = rewrite(open(os.path.join(src, f), encoding="utf-8").read(), ingot, deps)
        parts.append("\npub mod %s {\n%s}\n" % (f[:-3], indent(body.rstrip() + "\n", 4)))
    return "pub mod %s {\n%s}\n" % (ingot, indent("".join(parts), 4))


def main():
    out = [
        "// GENERATED by tools/gen_wasm.py from ingots/tensile and ingots/model. Do not edit.\n",
        "// One standalone file, because `fe build --backend wasm` does not take ingots.\n\n",
    ]
    for ingot, deps in ORDER:
        out.append(ingot_module(ingot, deps))
        out.append("\n")
    out.append(open(ENTRY, encoding="utf-8").read())
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("".join(out))
    print("wrote %s, %d bytes" % (os.path.relpath(OUT, ROOT), sum(len(p) for p in out)))


if __name__ == "__main__":
    main()
