#!/bin/bash
# Makes (or refreshes) an Fe workspace for one dense model. Its ingots depend on this repository's
# `tensile` and `dispute` ingots by relative path:
#
#   ingots/model     kernel constants, overflow proofs, reference tests      tools/gen_fe.py
#   ingots/arbiter   the dispute contract and its contract tests             tools/gen_arbiter.py
#   ingots/cli       a native classifier (`cli`, `cli trace`) for differential tests against the
#                    reference: the shipped ingots/cli without its auditor, which is fixed to the
#                    shipped model
#   ingots/network   only with `network`: the whole forward pass on-chain    tools/gen_network.py
#   build/tree.json  the model's neuron tree (root, leaves, proofs)          tools/gen_tree.py
#
# usage: gen_workspace.sh <model.json> <vectors-dir> <workspace-dir> [samples] [network]
#   <vectors-dir> holds inputs.bin and trace.jsonl for the model (docs/spec.md section 6), written
#   by the reference (tools/ref_vectors.py); the first [samples] (default 3, at least 2) become Fe
#   unit tests of the model ingot.
#
# The files named above and the fe.toml files are overwritten. Other ingots found under
# <workspace-dir>/ingots (your own contracts) are kept and listed as workspace members.
# Then: `cd <workspace-dir> && fe test && fe build`.
export PATH="$HOME/.fe/bin:$HOME/.foundry/bin:$PATH"
set -e
if [ $# -lt 3 ]; then
  echo "usage: gen_workspace.sh <model.json> <vectors-dir> <workspace-dir> [samples] [network]" >&2
  exit 2
fi
root="$(cd "$(dirname "$0")/.." && pwd)"
model="$1"
vectors="$2"
dir="$3"
samples="${4:-3}"
network="$5"
mkdir -p "$dir/ingots/model/src" "$dir/ingots/arbiter/src" "$dir/ingots/cli/src" "$dir/build"
[ "$network" = network ] && mkdir -p "$dir/ingots/network/src"
dir="$(cd "$dir" && pwd)"
name="$(python3 -c 'import json, sys; print(json.load(open(sys.argv[1]))["name"])' "$model")"
# The path from an ingot directory of the workspace to this repository's ingots.
up="$(python3 -c 'import os, sys; print(os.path.relpath(sys.argv[1], sys.argv[2]).replace(os.sep, "/"))' "$root/ingots" "$dir/ingots/model")"

ingot() {
  # ingot <name> <dependency lines...>: writes ingots/<name>/fe.toml
  local ingot_name="$1"
  shift
  {
    printf '[ingot]\nname = "%s"\nversion = "0.1.0"\n\n[dependencies]\n' "$ingot_name"
    printf '%s\n' "$@"
  } > "$dir/ingots/$ingot_name/fe.toml"
}
tensile="tensile = { path = \"$up/tensile\" }"
dispute="dispute = { path = \"$up/dispute\" }"
ingot model "$tensile"
ingot arbiter "$tensile" "$dispute" "model = true"
ingot cli "$tensile" "model = true"
[ "$network" = network ] && ingot network "$tensile" "model = true"

# Every ingot directory is a workspace member: the generated ones first, then any others.
members=""
for member in model arbiter cli network $(cd "$dir/ingots" && ls); do
  [ -f "$dir/ingots/$member/fe.toml" ] || continue
  case ", $members" in *"name = \"$member\""*) continue ;; esac
  members="$members{ path = \"ingots/$member\", name = \"$member\" }, "
done
cat > "$dir/fe.toml" <<EOF
[workspace]
name = "$name"
version = "0.1.0"
members = [${members%, }]
EOF

python3 "$root/tools/gen_fe.py" --model "$model" --vectors "$vectors" --samples "$samples" --out "$dir/ingots/model/src"
python3 "$root/tools/gen_arbiter.py" --model "$model" --vectors "$vectors" --samples "$samples" --lib --out "$dir/ingots/arbiter/src"
python3 "$root/tools/gen_tree.py" --model "$model" --out "$dir/build/tree.json"
if [ "$network" = network ]; then
  python3 "$root/tools/gen_network.py" --model "$model" --out "$dir/ingots/network/src"
fi

# The native classifier: the shipped reader and printer unchanged, and the shipped entry point
# without the audit mode.
cp "$root/ingots/cli/src/input.fe" "$root/ingots/cli/src/output.fe" "$dir/ingots/cli/src/"
cat > "$dir/ingots/cli/src/lib.fe" <<'EOF'
//! GENERATED by tools/gen_workspace.sh. Do not edit.
//!
//! `cli`: the native command-line classifier of this workspace's model, for
//! differential tests against the reference (`tools/diff_native.py`). It is
//! `ingots/cli` of the Tensile repository without its auditor: `input.fe` and
//! `output.fe` are copies, and this file is its entry point without `audit`.
//!
//! Reads from standard input until it ends. A sample is one byte per input
//! activation, each 0..127 (`docs/spec.md` section 6).
//!
//! - `cli` prints the predicted class of every sample, one per line.
//! - `cli trace` prints, for every sample, one `hidden K v v ..` line per
//!   hidden layer, then `logits v v ..`, then `class c`.
//!
//! Exit status: 0 on success, 1 for an unknown argument, 2 for malformed
//! input (a byte above 127, or input that ends inside a sample).
use model::{Input, classify, forward}
use std::io::{Read, Write, host, write}
use std::native::Args
use tensile::{Activations, Probe}

use input::{Chunk, is_word, read_chunk}
use output::{Printer, write_class, write_logits}

const OK: i32 = 0
const USAGE: i32 = 1
const MALFORMED: i32 = 2

/// The entry point: `cli` or `cli trace`.
pub fn main(argc: i32, argv: **u8) -> i32 {
    // `argc` and `argv` are the pair the entry bridge passes to `main`.
    let args = unsafe {
        Args::new(argc, argv)
    }
    let trace = if args.len() == 1 {
        false
    } else if args.len() == 2 && is_word(args.get(1), "trace") {
        true
    } else {
        return USAGE
    }
    with (Read = host(), Write = host()) {
        run(trace)
    }
}

/// Classifies every sample on standard input and returns the exit status.
fn run(trace: bool) -> i32 uses (r: mut Read, w: mut Write) {
    var status = OK
    var reading = true
    while reading {
        match read_chunk() {
            Chunk::Full(values) => {
                let x: Input = Activations::pack(values)
                if trace {
                    var printer = Printer::new()
                    let logits = with (Probe = printer) {
                        forward(x)
                    }
                    write_logits(logits)
                    write("class ")
                    write_class(logits.argmax())
                } else {
                    write_class(classify(x))
                }
            },
            Chunk::End => {
                reading = false
            },
            Chunk::Malformed => {
                status = MALFORMED
                reading = false
            },
        }
    }
    status
}
EOF
fe fmt "$dir/ingots" > /dev/null
echo "workspace $dir: ingots $(cd "$dir/ingots" && ls | tr '\n' ' ')for $name"
