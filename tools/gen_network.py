"""Generate an on-chain `Network` (the whole forward pass in one call) for a Tensile model.

Usage:
    python tools/gen_network.py [--model ref/out/model.json] --out DIR

Writes DIR/lib.fe, the root of a contract ingot that depends on `tensile` and on the model ingot
`tools/gen_fe.py` writes from the same model file. It follows the hand-written
`ingots/onchain/src/{network,rows}.fe` of the shipped model, for any number of layers:

- The weights of layer 1 do not fit one contract (a contract may hold 24,576 bytes), so they are
  split over weight contracts `Rows0`, `Rows1`, ..., each holding as many rows, with their biases,
  as fit in 23,800 bytes. `Network` reads one row and its bias per neuron with a STATICCALL and
  runs `layer1::neuron` on them. (The hand-written `Network` keeps the 32 biases of layer 1 in its
  own code; with 128 they are 4,096 bytes there and the contract no longer fits, so here they
  travel with their rows.)
- Every later layer is in `Network`'s own code and runs through its `apply`. If those layers are
  too large for one contract the build still succeeds, and `tools/check_size.sh` reports it.

This is here to MEASURE what a full on-chain run costs, the figure a dispute is compared with. It
is not identity-checked against the hand-written `Network` (the shipped one uses two named weight
contracts, `RowsLow` and `RowsHigh`); `tools/network_gas.sh` checks its results against the
reference instead. The output is laid out simply: run `fe fmt` afterwards. Standard library only.

A model with a convolution (docs/spec.md section 8) gets a `Network` with every layer in its own
code and no weight contracts (`conv_network_source`).
"""

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from gen_arbiter import ModelError, Shape, words  # noqa: E402

I1 = "    "
I2 = I1 * 2
I3 = I1 * 3

# Bytes of rows and biases one weight contract holds at most; the rest of the 24,576 is its code.
ROW_BYTES_PER_CONTRACT = 23800


def rows_per_contract(shape):
    """A row takes its packed words and one more word for its bias."""
    return max(1, ROW_BYTES_PER_CONTRACT // (32 * (words(shape.n_in) + 1)))


def holders(shape):
    """[(first row, row count)] of every weight contract."""
    per = rows_per_contract(shape)
    return [(first, min(per, shape.outs[0] - first)) for first in range(0, shape.outs[0], per)]


def conv_network_source(model):
    """`Network` for a model with a convolution: every layer in the contract's own code, through
    its `apply`. A convolution's weights are few (one row per filter), so there are no weight
    contracts; `tools/check_size.sh` reports it if the contract does not fit."""
    s = Shape(model)
    w_in = words(s.n_in)
    sizes = " -> ".join([str(s.n_in)] + [str(n) for n in s.outs])
    kinds = ", ".join("%s %d" % ("conv" if s.is_conv(k) else "dense", k) for k in s.layers())
    hidden_types = ["Activations<%d, %d>" % (s.outs[k - 1], s.frac[k - 1]) for k in s.hiddens()]
    trace_fe = ", ".join(["[u256; %d]" % s.hid_words(k) for k in s.hiddens()] + ["[i32; %d]" % s.classes])
    result = ["hidden%d" % k for k in s.hiddens()] + ["logits"]
    out = [
        "//! GENERATED by tools/gen_network.py from the model \"%s\". Do not edit." % model["name"],
        "//!",
        "//! `Network`: the whole forward pass of the network %s (%s) in one call," % (sizes, kinds),
        "//! every layer in the contract's own code through the model ingot's `apply`, which calls",
        "//! `tensile`: the code the arbiter re-runs one neuron or one filter of.",
        "use model::{Input, Logits, %s}" % ", ".join("layer%d" % k for k in s.layers()),
        "use tensile::Activations",
        "",
        "/// Runs the network on an input given as packed words (`docs/spec.md`",
        "/// section 7). A malformed input reverts.",
        "pub msg NetworkMsg {",
        I1 + "/// The predicted class, 0..%d." % (s.classes - 1),
        I1 + '#[selector = sol("classify(uint256[%d])")]' % w_in,
        I1 + "Classify { x: [u256; %d] } -> u256," % w_in,
        I1 + "/// Every hidden vector as packed words, in layer order, and the logits.",
        I1 + '#[selector = sol("trace(uint256[%d])")]' % w_in,
        I1 + "Trace { x: [u256; %d] } -> (%s)," % (w_in, trace_fe),
        "}",
        "",
        "/// The network %s on the EVM." % sizes,
        "pub contract Network {",
        I1 + "recv NetworkMsg {",
        I2 + "Classify { x } -> u256 {",
        I3 + "let (%s) = forward(x: Activations::from_words(x))" % ", ".join(["_"] * s.hidden_count + ["logits"]),
        I3 + "logits.argmax() as u256",
        I2 + "}",
        "",
        I2 + "Trace { x } -> (%s) {" % trace_fe,
        I3 + "let (%s) = forward(x: Activations::from_words(x))" % ", ".join(result),
        I3 + "(%s, logits.values())" % ", ".join("hidden%d.words()" % k for k in s.hiddens()),
        I2 + "}",
        I1 + "}",
        "}",
        "",
        "/// The forward pass: every hidden vector and the logits.",
        "fn forward(x: Input) -> (%s, Logits) {" % ", ".join(hidden_types),
        I1 + "let hidden1 = layer1::apply(x)",
    ]
    for k in range(2, s.count):
        out.append(I1 + "let hidden%d = layer%d::apply(x: hidden%d)" % (k, k, k - 1))
    out += [
        I1 + "let logits = layer%d::apply(x: hidden%d)" % (s.count, s.count - 1),
        I1 + "(%s)" % ", ".join(result),
        "}",
        "",
    ]
    return "\n".join(out)


def network_source(model):
    if any(layer.get("kind") == "conv1d" for layer in model["layers"]):
        return conv_network_source(model)
    s = Shape(model)
    w_in = words(s.n_in)
    fw1 = model["layers"][0]["weight_frac_bits"]
    row_type = "Row<%d, %d>" % (s.n_in, fw1)
    parts = holders(s)
    names = ["rows%d" % i for i in range(len(parts))]
    sizes = " -> ".join([str(s.n_in)] + [str(n) for n in s.outs])
    hidden_types = ["Activations<%d, %d>" % (s.outs[k - 1], s.frac[k - 1]) for k in s.hiddens()]
    trace_fe = ", ".join(["[u256; %d]" % s.hid_words(k) for k in s.hiddens()] + ["[i32; %d]" % s.classes])

    out = [
        "//! GENERATED by tools/gen_network.py from the model \"%s\". Do not edit." % model["name"],
        "//!",
        "//! `Network`: the whole forward pass of the network %s in one call, and the" % sizes,
        "//! weight contracts `Rows0` .. `Rows%d` that hold the rows of layer 1 (%d rows each at most)."
        % (len(parts) - 1, rows_per_contract(s)),
        "//! Every later layer is in `Network`'s code. All of it calls the `model` ingot, which calls",
        "//! `tensile`: the code the arbiter re-runs one neuron of.",
        "use model::{Input, Logits, %s}" % ", ".join("layer%d" % k for k in s.layers()),
        "use std::evm::{Address, Call}",
        "use tensile::{Activations, Q, Row}",
        "",
        "/// Asks a weight contract for one neuron of layer 1.",
        "pub msg RowMsg {",
        I1 + "/// Row `j` of the weights of layer 1, as packed words, and bias `j`.",
        I1 + '#[selector = sol("row(uint256)")]',
        I1 + "Row { j: usize } -> ([u256; %d], i32)," % w_in,
        "}",
        "",
    ]
    for i, (first, count) in enumerate(parts):
        out += [
            "/// Rows %d..%d of layer 1." % (first, first + count),
            "const ROWS_%d: [%s; %d] = [%s]" % (
                i, row_type, count, ", ".join("layer1::row(%d)" % j for j in range(first, first + count))),
            "/// Their biases.",
            "const BIAS_%d: [i32; %d] = [%s]" % (
                i, count, ", ".join(str(b) for b in model["layers"][0]["bias"][first:first + count])),
            "",
            "/// Holds rows %d..%d of layer 1 and their biases. Any other row reverts." % (first, first + count),
            "pub contract Rows%d {" % i,
            I1 + "recv RowMsg {",
            I2 + "Row { j } -> ([u256; %d], i32) {" % w_in,
            I3 + "(ROWS_%d[j%s].words(), BIAS_%d[j%s])" % (
                i, "" if first == 0 else " - %d" % first, i, "" if first == 0 else " - %d" % first),
            I2 + "}",
            I1 + "}",
            "}",
            "",
        ]
    out += [
        "/// Runs the network on an input given as packed words (`docs/spec.md`",
        "/// section 7). A malformed input reverts.",
        "pub msg NetworkMsg {",
        I1 + "/// The predicted class, 0..%d." % (s.classes - 1),
        I1 + '#[selector = sol("classify(uint256[%d])")]' % w_in,
        I1 + "Classify { x: [u256; %d] } -> u256," % w_in,
        I1 + "/// Every hidden vector as packed words, in layer order, and the logits.",
        I1 + '#[selector = sol("trace(uint256[%d])")]' % w_in,
        I1 + "Trace { x: [u256; %d] } -> (%s)," % (w_in, trace_fe),
        "}",
        "",
        "/// The network %s on the EVM." % sizes,
        "pub contract Network uses (call: Call) {",
    ]
    out += [I1 + "%s: Address," % name for name in names]
    out += [
        "",
        I1 + "init(%s) uses (%s) {" % (", ".join("holder%d: Address" % i for i in range(len(parts))),
                                      ", ".join("mut %s" % name for name in names)),
    ]
    out += [I2 + "%s = holder%d" % (name, i) for i, name in enumerate(names)]
    out += [I1 + "}", "", I1 + "recv NetworkMsg {"]
    uses = "uses (call, %s)" % ", ".join(names)
    passed = ", ".join(names)
    result = ["hidden%d" % k for k in s.hiddens()] + ["logits"]
    out += [
        I2 + "Classify { x } -> u256 %s {" % uses,
        I3 + "let (%s) = forward(x: Activations::from_words(x), %s)" % (
            ", ".join(["_"] * s.hidden_count + ["logits"]), passed),
        I3 + "logits.argmax() as u256",
        I2 + "}",
        "",
        I2 + "Trace { x } -> (%s) %s {" % (trace_fe, uses),
        I3 + "let (%s) = forward(x: Activations::from_words(x), %s)" % (", ".join(result), passed),
        I3 + "(%s, logits.values())" % ", ".join("hidden%d.words()" % k for k in s.hiddens()),
        I2 + "}",
        I1 + "}",
        "}",
        "",
        "/// The forward pass: every hidden vector and the logits. One function for both handlers, so",
        "/// that the weights of the later layers are in the contract's code once.",
        "fn forward(x: Input, %s) -> (%s, Logits) uses (call: Call) {" % (
            ", ".join("%s: Address" % name for name in names), ", ".join(hidden_types)),
        I1 + "let hidden1 = first_layer(x, %s)" % passed,
    ]
    for k in range(2, s.count):
        out.append(I1 + "let hidden%d = layer%d::apply(x: hidden%d)" % (k, k, k - 1))
    out += [
        I1 + "let logits = layer%d::apply(x: hidden%d)" % (s.count, s.count - 1),
        I1 + "(%s)" % ", ".join(result),
        "}",
        "",
        "/// Layer 1, one neuron at a time: `layer1::neuron` on a row and bias fetched from",
        "/// the weight contract that holds them.",
        "fn first_layer(x: Input, %s) -> %s uses (call: Call) {" % (
            ", ".join("%s: Address" % name for name in names), hidden_types[0]),
        I1 + "var values: [i8; %d] = [0; %d]" % (s.outs[0], s.outs[0]),
        I1 + "for j in 0 .. %d {" % s.outs[0],
    ]
    chain = ""
    for i, (first, count) in enumerate(parts):
        if i == len(parts) - 1:
            chain += "{ %s }" % names[i]
        else:
            chain += "if j < %d { %s } else " % (first + count, names[i])
    out += [
        I2 + "let holder = %s" % chain,
        I2 + "let (row, bias) = holder.static(RowMsg::Row { j })",
        I2 + "values[j] = layer1::neuron(row: Row::from_words(row), x, bias: Q::from_raw(bias))",
        I1 + "}",
        I1 + "Activations::pack(values)",
        "}",
        "",
    ]
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--model", default=os.path.join(ROOT, "ref", "out", "model.json"))
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    with open(args.model, "r", encoding="utf-8") as f:
        model = json.load(f)
    try:
        source = network_source(model)
    except ModelError as error:
        print("gen_network: %s" % error, file=sys.stderr)
        return 1
    os.makedirs(args.out, exist_ok=True)
    path = os.path.join(args.out, "lib.fe")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    print("wrote %s (%d bytes)" % (path, len(source)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
